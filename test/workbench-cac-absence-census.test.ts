const escapeRe = (text: string): string => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const alternative = (needle: Needle): string => (needle.word ? `(?<![A-Za-z0-9_])${escapeRe(needle.text)}(?![A-Za-z0-9_])` : escapeRe(needle.text));
