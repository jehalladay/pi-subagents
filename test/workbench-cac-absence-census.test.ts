const DEPENDENCY_MAPS: readonly string[] = ["dependencies", "devDependencies", "peerDependencies", "optionalDependencies"];
const BUNDLED: readonly string[] = ["bundleDependencies", "bundledDependencies"];
const isRecord = (value: unknown): value is Record<string, unknown> => typeof value === "object" && value !== null && !Array.isArray(value);
/** Every package name and dependency spec a manifest or a lock carries. */
function manifestRead(json: unknown): Manifest {
  const names: string[] = [];
  const specs: string[] = [];
  const entry = (value: unknown): void => {
    if (!isRecord(value)) return;
    if (typeof value.name === "string") names.push(value.name);
    if (typeof value.resolved === "string") specs.push(value.resolved);
    for (const map of DEPENDENCY_MAPS) {
      const deps = value[map];
      if (!isRecord(deps)) continue;
      for (const [name, spec] of Object.entries(deps)) {
        names.push(name);
        if (typeof spec === "string") specs.push(spec);
      }
    }
    for (const list of BUNDLED) {
      const bundled = value[list];
      if (Array.isArray(bundled)) for (const name of bundled) if (typeof name === "string") names.push(name);
    }
  };
  entry(json);
  if (isRecord(json) && isRecord(json.packages)) {
    for (const [path, value] of Object.entries(json.packages)) {
      const at = path.lastIndexOf("node_modules/");
      if (at >= 0) names.push(path.slice(at + "node_modules/".length));
      entry(value);
    }
  }
  return { names: [...new Set(names)].sort(), specs: [...new Set(specs)].sort() };
}
const segments = (part: string): string[] => part.toLowerCase().split(/[-._]/);
