/** A quoted run (wb-xvmw NAMING): one quoted path literal, or a join's comma-separated quoted literals, with no quoted argument before it. */
const QUOTED_RUN = /(?<!["'`]\s*,\s*)["'`][\w./-]*["'`](?:\s*,\s*["'`][\w./-]*["'`])*/g;
/** The test/fixtures/ paths a census module's text NAMES (the wb-xvmw reading, as test/workbench-hx-cost-certificate-census.test.ts
 * reads it): a path token spelling test/fixtures/<p>, or a quoted run whose segments, joined with slashes and a leading ./ dropped,
 * spell fixtures/<p> or test/fixtures/<p>. A basename alone names nothing. */
function fixtureNames(text: string): string[] {
  const tokens = (text.match(/[\w./-]+/g) ?? []).map(token => token.replace(/\.+$/, ""));
  const runs = (text.match(QUOTED_RUN) ?? []).map(run => run.split(/["'`]\s*,\s*["'`]/).join("/").slice(1, -1).replace(/^\.\//, ""));
  return [...tokens.filter(token => token.startsWith("test/fixtures/")), ...runs.flatMap(run => (run.startsWith("fixtures/") ? [`test/${run}`] : run.startsWith("test/fixtures/") ? [run] : []))];
}
function walk(root: string, dir: string, unread: string[]): string[] {
  if (!existsSync(join(root, dir))) return [];
  return readdirSync(join(root, dir), { withFileTypes: true })
    .flatMap(entry => {
      const path = `${dir}/${entry.name}`;
      if (entry.isDirectory()) return walk(root, path, unread);
      if (entry.isFile()) return [path];
      unread.push(path);
      return [];
    })
    .sort();
}
/** The five trees of a root read by class: product hits (the bound sentence in docs/18 blanked first), test/ hits in and outside a
 * holder, every bound-sentence site in product scope, and the entries the walk could not read. */
function treeCensus(root: string): Census {
  const unread: string[] = [];
  const perRoot: Record<string, number> = {};
  const files = ROOTS.flatMap(dir => {
    const found = walk(root, dir, unread);
    perRoot[dir] = found.length;
    return found;
  });
  const texts = new Map(files.map(file => [file, readFileSync(join(root, file), "latin1")]));
  const modules = files.filter(file => HOLDER_MODULE.test(file));
  const named = new Set(modules.flatMap(file => fixtureNames(texts.get(file) ?? "")));
  const holders = new Set([...modules, ...files.filter(file => file.startsWith("test/fixtures/") && named.has(file))]);
  const bound = latin1(STATEMENT.sentence);
  const product: Hit[] = [];
  const outside: Hit[] = [];
  const holder: Hit[] = [];
  const sites: string[] = [];
  for (const file of files) {
    let text = texts.get(file) ?? "";
    const inProduct = PRODUCT.some(dir => file.startsWith(`${dir}/`));
    if (inProduct) {
      const lines = text.split("\n");
      for (let index = 0; index < lines.length; index += 1) {
        for (let at = (lines[index] ?? "").indexOf(bound); at >= 0; at = (lines[index] ?? "").indexOf(bound, at + 1)) sites.push(`${file}:${index + 1}`);
      }
      if (file === DOCS_FILE) text = text.replaceAll(bound, " ".repeat(bound.length));
    }
    const hits = hitsIn(file, text);
    if (inProduct) product.push(...hits);
    else if (holders.has(file)) holder.push(...hits);
    else outside.push(...hits);
  }
  return { files, perRoot, unread, product, outside, holder, bound: sites };
}
