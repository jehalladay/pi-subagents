/** An owner filing: the first paragraphs of a bead's notes in the tracked export, each trimmed. bd appends a later note after one
 * newline, so the filing's last paragraph loses its trailing newline to the first blank line an append makes (measured on a scratch
 * store); trimming keeps the hashed text identical before and after every append. Two filings are read: wb-zzb4's (the base) and
 * wb-rdlh.2's (the extension). */
function filing(bead: string, paragraphs: number): string {
  const rows = readFileSync(join(REPO, EXPORT_FILE), "utf8")
    .split("\n")
    .filter(line => line.includes(`"${bead}"`))
    .map(line => JSON.parse(line) as { readonly id?: unknown; readonly notes?: unknown })
    .filter(row => row.id === bead);
  const notes = rows.length === 1 ? rows[0]?.notes : undefined;
  if (typeof notes !== "string") throw new Error(`${EXPORT_FILE} carries ${rows.length} ${bead} rows; the census needs exactly one, with notes`);
  return notes
    .split(/\n\s*\n/)
    .slice(0, paragraphs)
    .map(paragraph => paragraph.trim())
    .join("\n\n");
}
/** The filing's identifier-set clause, its bound sentence and its acceptance clause (the parse anchors spell no needle). */
const SET_CLAUSE = /for the identifier set \(the (\d+) schema names of ([\d/]+) — (\S+) through (\S+) — plus (.+?) and the word (\S+)\) returns 0 hits/;
const SENTENCE_CLAUSE = /gains one falsifiable sentence \((.+?)\) bound by that census/;
const ACCEPTANCE_CLAUSE = /Acceptance, hermetic \([^)]*\): (.+? bound by that census)\./;
function statement(text: string): Statement {
  const set = SET_CLAUSE.exec(text);
  const sentence = SENTENCE_CLAUSE.exec(text);
  const acceptance = ACCEPTANCE_CLAUSE.exec(text);
  if (set === null || sentence === null || acceptance === null) throw new Error("the filing no longer carries its identifier-set, sentence and acceptance clauses");
  const [, count = "", files = "", first = "", last = "", plus = "", word = ""] = set;
  return { count: Number(count), files: files.split("/"), first, last, plus: plus.split(", "), word, sentence: sentence[1] ?? "", acceptance: acceptance[1] ?? "" };
}
/** The extension filing's clauses: members, range, the member the base already holds, the derivation pin and the acceptance clause
 * (the parse anchors spell no needle). */
const EXT_SET_CLAUSE = /vocabulary added since ([0-9a-f]{12}): the (\d+) V0\/V1\/V2 names of the (\d+) new files, (.+?), plus pre-existing (.+?) missing from its base set/;
const EXT_RANGE_CLAUSE = /(\d+) new V0\/V1\/V2 names \((\S+?)\.\.(\S+?); none at ([0-9a-f]{12})\)/;
const EXT_HELD_CLAUSE = /, (\S+) already in it\)/;
const EXT_PIN_CLAUSE = /\.md:\d+@([0-9a-f]{12})/;
const EXT_ACCEPTANCE_CLAUSE = /Acceptance: (\(a\) [^\n]+)\./;
function extensionStatement(text: string): Extension {
  const set = EXT_SET_CLAUSE.exec(text);
  const range = EXT_RANGE_CLAUSE.exec(text);
  const held = EXT_HELD_CLAUSE.exec(text);
  const pin = EXT_PIN_CLAUSE.exec(text);
  const acceptance = EXT_ACCEPTANCE_CLAUSE.exec(text);
  if (set === null || range === null || held === null || pin === null || acceptance === null) throw new Error("the extension filing no longer carries its member, range, held, pin and acceptance clauses");
  const [, since = "", count = "", files = "", added = "", earlier = ""] = set;
  const [, ranged = "", first = "", last = "", none = ""] = range;
  if (ranged !== count) throw new Error(`the extension filing counts ${count} and ${ranged} schema names`);
  return { count: Number(count), files: Number(files), members: [...added.split(", "), ...earlier.split(" and ")], first, last, held: held[1] ?? "", since, none, pin: pin[1] ?? "", acceptance: acceptance[1] ?? "" };
}
