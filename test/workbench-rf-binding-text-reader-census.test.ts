  if (at.probe === "claim-rows") return claimLabels();
  if (at.probe === "export-rows") return exportRequirements();
  if (at.probe === "member-pins") return MEMBERS.flatMap((member) => [member.id, ...(member.twins ?? [])].map((id) => `${id}:${member.form}`));
