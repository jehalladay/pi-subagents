/** Section body lines: after the exact "## heading" line, bounded at the next level-1 or level-2 heading (or EOF). */
function sectionLines(doc: string, heading: string): string[] | undefined {
  const lines = doc.split("\n");
  const at = lines.indexOf(`## ${heading}`);
  if (at < 0) return undefined;
  const rest = lines.slice(at + 1);
  const next = rest.findIndex((line) => /^#{1,2} /u.test(line));
  return next < 0 ? rest : rest.slice(0, next);
}

const FROZEN_SECTIONS: readonly (readonly [Section, string])[] = [
  [SEC_UI, UI_PARAGRAPH],
  [SEC_RULINGS, RULING_LINES.join("\n")],
];

/**
 * One text view throughout: the raw docs lines. Uniqueness of the exact heading line and the extraction of its
 * body both read these lines, so a hidden copy (an HTML comment or a fenced block holding a second heading) is
 * counted by the same view that extracts, and a comment inside a section is a body line that breaks equality.
 */
function auditDocs(doc: string): string[] {
  const problems: string[] = [];
  const lines = doc.split("\n");
  const order: number[] = [];
  for (const [heading, expected] of FROZEN_SECTIONS) {
    const headings = lines.filter((line) => line === `## ${heading}`).length;
    if (headings !== 1) {
      problems.push(`[docs-heading] ${DOC} has ${headings} lines exactly "## ${heading}", expected one`);
      continue;
    }
    order.push(lines.indexOf(`## ${heading}`));
    const body = (sectionLines(doc, heading) ?? []).filter((line) => line.trim().length > 0).join("\n");
    if (body !== expected) problems.push(`[docs-section] ${DOC} section "${heading}" is not the exact frozen body (every sentence, every numbered line, nothing added)`);
  }
  if (order.length === 2 && (order[0] ?? 0) >= (order[1] ?? 0)) problems.push(`[docs-order] ${DOC} no longer lists "UI integration" before "Owner rulings on the design conflicts"`);
  return problems;
}

