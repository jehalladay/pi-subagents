/** Violations of one row, each beginning with `<row id>/<half id>`. Empty only when every pin is live and honest. */
function rowViolations(row: Row, listing: readonly ListedCase[], locate: (file: string) => PinLocation, gateConfig: GateConfig, forgeToml: string): string[] {
  const out: string[] = [];
  for (const half of row.halves) {
    const where = `${row.id}/${half.id}`;
    if (!row.quote.length || !(row.quote === half.clause || row.quote.includes(half.clause))) out.push(`${where}: clause is not part of the row quote`);
    if (half.status !== "pinned") {
      if (half.pins.length > 0) out.push(`${where}: a ${half.status} half carries pins`);
      if ((half.reason ?? "").trim().length < 40) out.push(`${where}: a ${half.status} half carries no reason`);
      continue;
    }
    if (half.pins.length === 0) out.push(`${where}: a pinned half holds no pin`);
    if (half.reason !== undefined) out.push(`${where}: carries both pins and an unpinned reason`);
    for (const pin of half.pins) {
      if (!pin.file.startsWith("test/")) out.push(`${where}: ${pin.file} is not under test/`);
      const tier = auditTier(pin, gateConfig, forgeToml);
      if (tier) out.push(`${where}: ${pin.file} :: ${pin.title}: ${tier}`);
      const location = locate(pin.file);
      const focus = auditFocus(location.source);
      if (focus) out.push(`${where}: ${pin.file}: ${focus}`);
      const problem = auditPin(listing, location.absolute, location.source, pin);
      if (problem) out.push(`${where}: ${pin.file} :: ${pin.title}: ${problem}`);
    }
  }
  return out;
}

