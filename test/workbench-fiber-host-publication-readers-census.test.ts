    expect(Object.keys(SCRIPT_KINDS).filter(extension => !(SCRIPT_PLANTS.script as readonly string[]).includes(extension)), "G26 plants every SCRIPT_KINDS key").toEqual([]);
    expect(HOSTED_CLASSES.filter(name => !Object.hasOwn(HOSTING_SPELLINGS, name)), "G24 plants every hosted class").toEqual([]);
