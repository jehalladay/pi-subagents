/** An object `depth` levels deep with the leaf innermost. */
function nested(depth: number, leaf: { [key: string]: unknown }): { [key: string]: unknown } {
  return depth <= 1 ? leaf : { [`level${depth}`]: nested(depth - 1, leaf) };
}
/** One fold axis: every FOLD_FORMS spelling placed alone in the criterion's field (meeting it), every FOLD_QUIET one (meeting none). */
function foldPlants(criterion: "id" | "permission" | "contract", place: (spelling: string) => Partial<CapabilityDescriptor>): Record<string, DescriptorPlant> {
  const held = Object.entries(FOLD_FORMS).map(([name, spelling]): [string, DescriptorPlant] => [`${criterion} ${name}`, { descriptor: plainDescriptor(place(spelling)), criteria: [criterion] }]);
  const quiet = Object.entries(FOLD_QUIET).map(([name, spelling]): [string, DescriptorPlant] => [`${criterion} quiet ${name}`, { descriptor: plainDescriptor(place(spelling)), criteria: [] }]);
  return Object.fromEntries([...held, ...quiet]);
}
/** A publication entry in camel case (queueValuePublication). */
function camel(entry: string): string {
  return entry
    .split("_")
    .map((part, index) => (index === 0 ? part : `${part.charAt(0).toUpperCase()}${part.slice(1)}`))
    .join("");
}
