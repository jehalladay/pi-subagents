/** The Ownership boundaries section of a docs/03 page: the shared binding (sectionTables and docsSection, one binding), every top-level table's rows read rendered, and the blocks no row reading reaches. */
function ownershipOf(page: string): Ownership {
  const bound = sectionTables(page, OWNERSHIP_HEADING, SECTION_DEPTH, [DOCS_03_TITLE]);
  const section = docsSection(page, OWNERSHIP_HEADING, SECTION_DEPTH, [DOCS_03_TITLE]);
  const refused = (why: string): Ownership => ({ ok: false, why, headers: [], rows: [], cells: [], unread: [] });
  if (!bound.ok || !section.ok) return refused(bound.ok ? section.why : bound.why);
  const shared = section.blocks.flatMap(block => (block.kind === "other" && block.type === "table" ? [block.text] : []));
  const mine = bound.grids.map(grid => collapse(grid.flat().map(shownCell).join(" ")));
  const differing = mine.length === shared.length ? mine.findIndex((text, index) => text !== shared[index]) : Math.min(mine.length, shared.length);
  if (differing >= 0) return refused(`table ${differing + 1}: the rendered cells disagree with the shared rendered view (${mine.length} tables read, ${shared.length} rendered)`);
  const unread = [...(section.hasHtml ? ["html"] : []), ...section.blocks.map(kindOf).filter(kind => kind !== "html" && !READ_KINDS.includes(kind))];
  const bodies = bound.grids.flatMap(grid => grid.slice(1));
  return {
    ok: true,
    why: "",
    headers: bound.grids.map(grid => (grid[0] ?? []).map(renderedCell)),
    rows: bodies.map(cells => ({ concern: renderedCell(cells[0] ?? ""), owner: renderedCell(cells[1] ?? ""), may: renderedCell(cells[2] ?? "") })),
    cells: bodies.map(cells => [...cells.map(renderedCell), ...cells]),
    unread,
  };
}
