  if (node === "item") return { ...wiring, evidence: wiring.evidence.map(item => put(item)) };
  if (node === "sources") return { ...wiring, sources: put(wiring.sources) };
  if (node === "source") return { ...wiring, sources: wiring.sources.map(item => put(item)) };
