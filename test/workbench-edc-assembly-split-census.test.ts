/** The quotes tile the label in order, with nothing but separators (whitespace, comma, semicolon, colon, parentheses) between. */
function tiles(label: string, quotes: readonly string[]): boolean {
  let cursor = 0;
  for (const quote of quotes) {
    const found = quote === "" ? -1 : label.indexOf(quote, cursor);
    if (found < 0 || !/^[\s,;:()]*$/.test(label.slice(cursor, found))) return false;
    cursor = found + quote.length;
  }
  return /^[\s,;:()]*$/.test(label.slice(cursor));
}
/** The split as a sentence lists it: clauses at "; ", ", " or " and ", each an owner and its duty. */
const splitOf = (clause: string): string[] =>
  clause
    .split(/; |, | and /)
    .map(part => part.trim().replace(/\.$/, ""))
    .filter(part => part !== "");
/** The producer Authority line's split: its second sentence. */
const producerSplit = (text: string): string[] => splitOf(text.split(". ")[1] ?? "");
/** The export's bindings over a row table: one finding per binding that fails, none when the table is the filing's. */
function exportFindings(rows: readonly Row[], quotes: Readonly<Record<string, string>>, title: string, notes: string): string[] {
  const findings: string[] = [];
  const label = (id: string): string => rows.find(entry => entry.id === id)?.label ?? "-";
  if (title !== `[${REQUIREMENT}] ${label("T")}, ${label("S1")} and ${label("S2")}${DASH}${label("S3")}${DASH}${label("S4")}. Artifact: ${label("N")}.`) {
    findings.push("the title is the requirement id and rows T, S1-S4 and N's labels");
  }
  const groups = CITATION.exec(notes)?.groups;
  if (groups?.a1 !== label("A1") || groups?.a2 !== label("A2")) findings.push("the acceptance sentence is rows A1 and A2");
  if (groups?.d1 !== label("D1") || groups?.d2 !== label("D2") || groups?.d3 !== label("D3")) findings.push("the citation's parentheticals are rows D1-D3");
  if (groups?.d4 !== label("D4")) findings.push("the citation's but-clause is row D4");
  for (const entry of rows) {
    if (entry.id !== "Q" && !tiles(entry.label, entry.pins.map(pin => quotes[pin] ?? ""))) findings.push(`row ${entry.id}'s pin quotes tile its label`);
  }
  return findings;
}

