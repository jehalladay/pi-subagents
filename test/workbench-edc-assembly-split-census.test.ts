const WIRE_FAULTS: Readonly<Record<Port, Fault>> = {
  "provider-query": "wire-provider-query",
  "coverage-mint": "wire-coverage-mint",
  "work-admission": "wire-work-admission",
  publication: "wire-publication",
  verification: "wire-verification",
};
const firstIndex = (evidence: readonly Evidence[], subject: string): number => evidence.findIndex(item => item.subject === subject);

function seamWith(faults: ReadonlySet<Fault>): SeamFactory {
  const has = (fault: Fault): boolean => faults.has(fault);
  return world => {
    let runs = 0;
    const handle =
      (port: Port): Handle =>
      subject =>
        world.effect(port, subject);
    return {
      wire(request) {
        const ports: Partial<Record<Port, Handle>> = {};
        for (const port of PORTS) {
          if (has(WIRE_FAULTS[port]) || (port === "provider-query" && has("query-through-wired-port"))) ports[port] = handle(port);
        }
        const subjects = has("demand-from-evidence") ? distinct(request.evidence.map(item => item.subject)) : [...request.subjects];
        return { demand: { owner: has("demand-owner-assembler") ? "assembler" : "host", subjects }, evidence: request.evidence, sources: request.sources, ports };
      },
      assemble(wiring) {
        runs += 1;
        let subjects: readonly string[] = wiring.demand.subjects;
        if (has("widen-demand")) subjects = distinct([...subjects, ...wiring.evidence.map(item => item.subject)]);
        if (has("evidence-order")) subjects = [...subjects].sort((left, right) => firstIndex(wiring.evidence, left) - firstIndex(wiring.evidence, right));
        const blocks: Block[] = [];
        const unmet: string[] = [];
        for (const subject of subjects) {
          let evidence: readonly Evidence[] = wiring.evidence.filter(item => item.subject === subject);
          if (evidence.length === 0 && has("query-missing-evidence")) evidence = world.effect("provider-query", subject);
          if (evidence.length === 0 && has("query-through-wired-port")) evidence = wiring.ports["provider-query"]?.(subject) ?? [];
          if (has("verify-unknown")) evidence = evidence.map(item => (item.value === "unknown" ? (world.effect("verification", subject)[0] ?? item) : item));
          if (has("re-evaluate-unknown")) evidence = evidence.map(item => (item.value === "unknown" ? { ...item, value: "false" as const } : item));
          if (has("drop-provenance")) evidence = evidence.map(item => ({ subject: item.subject, claim: item.claim, value: item.value }) as unknown as Evidence);
          if (has("first-evidence-only")) evidence = evidence.slice(0, 1);
          const supplied = wiring.sources.find(item => item.subject === subject)?.text;
          const text = supplied ?? (has("fabricate-source") && evidence.length > 0 ? evidence.map(item => item.claim).join(" ") : undefined);
          if (evidence.length > 0 && text !== undefined && !has("every-subject-unmet")) blocks.push({ subject, text, evidence });
          else if (!has("drop-unmet")) unmet.push(subject);
        }
        if (has("mint-coverage")) for (const block of blocks) world.effect("coverage-mint", block.subject);
        if (has("admit-unmet-work")) for (const subject of unmet) world.effect("work-admission", subject);
        if (has("publish-document")) world.effect("publication", subjects.join(","));
        if (has("mutate-input")) (wiring.sources as Source[]).reverse();
        if (has("empty-document")) return { blocks: [], unmet: [] };
        return { blocks: has("alternate-order") && runs % 2 === 0 ? [...blocks].reverse() : blocks, unmet };
      },
    };
  };
}
