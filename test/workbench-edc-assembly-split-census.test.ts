/** A module's code units: every identifier and private name, string, template part, regular expression and JSX text (no comment); a non-script file is one unit. */
function unitsOf(entry: Entry): string[] {
  const kind = SCRIPT_KINDS[extname(entry.path).toLowerCase()];
  if (kind === undefined) return [entry.text];
  const units: string[] = [];
  const visit = (node: ts.Node): void => {
    if (
      ts.isIdentifier(node) ||
      ts.isPrivateIdentifier(node) ||
      ts.isStringLiteral(node) ||
      ts.isNoSubstitutionTemplateLiteral(node) ||
      ts.isTemplateHead(node) ||
      ts.isTemplateMiddle(node) ||
      ts.isTemplateTail(node) ||
      ts.isRegularExpressionLiteral(node) ||
      ts.isJsxText(node)
    ) {
      units.push(node.text);
    }
    ts.forEachChild(node, visit);
  };
  visit(ts.createSourceFile(entry.path, entry.text, ts.ScriptTarget.Latest, false, kind));
  return units;
}
