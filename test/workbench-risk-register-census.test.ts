interface GateConfig {
  readonly include: readonly string[];
  readonly exclude: readonly string[];
}

function globToRegExp(glob: string): RegExp {
  let out = "";
  for (let i = 0; i < glob.length; i += 1) {
    const c = glob[i] ?? "";
    if (c === "*" && glob[i + 1] === "*") {
      if (glob[i + 2] === "/") {
        out += "(?:.*/)?";
        i += 2;
      } else {
        out += ".*";
        i += 1;
      }
    } else if (c === "*") out += "[^/]*";
    else out += c.replace(/[.+^${}()|[\]\\?]/gu, "\\$&");
  }
  return new RegExp(`^${out}$`, "u");
}

function matchesAny(patterns: readonly string[], file: string): boolean {
  return patterns.some((pattern) => globToRegExp(pattern).test(file));
}

function gateConfigOf(config: unknown): GateConfig {
  const test = (config as { test?: { include?: unknown; exclude?: unknown } }).test ?? {};
  const strings = (value: unknown): readonly string[] => (Array.isArray(value) ? value.filter((item): item is string => typeof item === "string") : []);
  return { include: strings(test.include), exclude: strings(test.exclude) };
}


interface TierClaim {
  readonly file?: string;
  readonly tier: Tier;
  readonly command?: string;
}

/** Names listed in the forge.toml `gate = [...]` array. */
function gateList(forgeToml: string): readonly string[] {
  const match = /^gate\s*=\s*\[([^\]]*)\]/mu.exec(forgeToml);
  return [...(match?.[1] ?? "").matchAll(/"([^"]+)"/gu)].map((item) => item[1] ?? "");
}

/** A tier label is a claim about the gate config: verify it, never carry it from prose. */
function auditTier(claim: TierClaim, gateConfig: GateConfig, forgeToml: string): string | undefined {
  if (claim.tier === "default-gate") {
    const file = claim.file ?? "";
    if (!matchesAny(gateConfig.include, file)) return `[tier-truth] ${file} is labelled default-gate but is not matched by the vitest include`;
    if (matchesAny(gateConfig.exclude, file)) return `[tier-truth] ${file} is labelled default-gate but is excluded from the vitest run`;
    return undefined;
  }
  if (claim.tier === "no-case") return claim.command === undefined && claim.file === undefined ? undefined : "[tier-truth] a no-case label names a file or command, which is a claim of evidence it does not have";
  if (!claim.command) return "[tier-truth] a bench-receipt label names no forge.toml command";
  if (!forgeToml.includes(`[build.commands.${claim.command}]`)) return `[tier-truth] the bench-receipt label names forge.toml command ${claim.command}, which does not exist`;
  if (gateList(forgeToml).includes(claim.command)) return `[tier-truth] the bench-receipt label names forge.toml command ${claim.command}, which runs in the default gate list, not as a separate receipt`;
  return undefined;
}

const pinClaim = (pin: Pin): TierClaim => ({ file: pin.file, tier: pin.tier, ...(pin.command === undefined ? {} : { command: pin.command }) });

