/** Section body lines: after the exact "## heading" line, bounded at the next level-1 or level-2 heading (or EOF). */
function sectionLines(doc: string, heading: string): string[] | undefined {
  const lines = doc.split("\n");
  const at = lines.indexOf(`## ${heading}`);
  if (at < 0) return undefined;
  const rest = lines.slice(at + 1);
  const next = rest.findIndex((line) => /^#{1,2} /u.test(line));
  return next < 0 ? rest : rest.slice(0, next);
}

function auditDocs(doc: string): string[] {
  const headings = doc.split("\n").filter((line) => line === `## ${SECTION}`).length;
  if (headings !== 1) return [`[docs-heading] ${DOC} has ${headings} lines exactly "## ${SECTION}", expected one`];
  const body = (sectionLines(doc, SECTION) ?? []).filter((line) => line.trim().length > 0);
  if (body.join("\n") !== SECTION_LINES.join("\n")) {
    const at = body.findIndex((line, index) => line !== SECTION_LINES[index]);
    const named = DOC_RISKS.find((risk) => (body[at] ?? "").includes(risk) || (SECTION_LINES[at] ?? "").includes(risk)) ?? "(header, prose or extra line)";
    return [`[docs-section] ${DOC} section "${SECTION}" is not the exact frozen body (every cell incl. Impact, the header, any prose; first difference at line ${at}, risk: ${named})`];
  }
  return [];
}

