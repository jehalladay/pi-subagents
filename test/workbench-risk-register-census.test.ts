/** Violations of one row, each beginning with `<row id>/<half id>`. Empty only when every pin is live and honest. */
function rowViolations(rowToAudit: Row, listing: readonly ListedCase[], locate: (file: string) => PinLocation, gateConfig: GateConfig, forgeToml: string): string[] {
  const out: string[] = [];
  for (const half of rowToAudit.halves) {
    const where = `${rowToAudit.id}/${half.id}`;
    if (!half.clause.length || !(rowToAudit.quote.includes(half.clause) || rowToAudit.risk.includes(half.clause))) out.push(`${where}: clause is not part of the Risk or Mitigation cell`);
    if (half.pins.length === 0) {
      if ((half.reason ?? "").trim().length < 40) out.push(`${where}: unpinned half carries no reason`);
      if (half.tier === undefined) out.push(`${where}: unpinned half carries no tier label`);
      else {
        const tier = auditTier({ tier: half.tier, ...(half.command === undefined ? {} : { command: half.command }) }, gateConfig, forgeToml);
        if (tier) out.push(`${where}: ${tier}`);
      }
      continue;
    }
    if (half.reason !== undefined) out.push(`${where}: carries both pins and an unpinned reason`);
    for (const pin of half.pins) {
      if (!pin.file.startsWith("test/")) out.push(`${where}: ${pin.file} is not under test/`);
      const tier = auditTier(pinClaim(pin), gateConfig, forgeToml);
      if (tier) out.push(`${where}: ${pin.file} :: ${pin.title}: ${tier}`);
      const location = locate(pin.file);
      const focus = auditFocus(location.source);
      if (focus) out.push(`${where}: ${pin.file}: ${focus}`);
      const problem = auditPin(listing, location.absolute, location.source, pin);
      if (problem) out.push(`${where}: ${pin.file} :: ${pin.title}: ${problem}`);
    }
  }
  return out;
}

