/** Blanks every comment (same length, so offsets survive) so a commented-out call is never located. */
function maskComments(s: string): string {
  let out = "";
  let i = 0;
  while (i < s.length) {
    const c = s[i] ?? "";
    const next = s[i + 1] ?? "";
    if (c === "/" && next === "/") {
      const eol = s.indexOf("\n", i);
      const end = eol < 0 ? s.length : eol;
      out += " ".repeat(end - i);
      i = end;
    } else if (c === "/" && next === "*") {
      const close = s.indexOf("*/", i + 2);
      const end = close < 0 ? s.length : close + 2;
      out += s.slice(i, end).replace(/[^\n]/gu, " ");
      i = end;
    } else if (c === "'" || c === '"' || c === "`") {
      let j = i + 1;
      while (j < s.length && s[j] !== c) j += s[j] === "\\" ? 2 : 1;
      out += s.slice(i, j + 1);
      i = j + 1;
    } else {
      out += c;
      i += 1;
    }
  }
  return out;
}

function titleLiterals(title: string): string[] {
  return ["'", '"', "`"].map((quote) => `${quote}${title}${quote}`);
}

/** Blanks every comment AND every string/template body (same length) so a focus call spelled in text never counts. */
function maskCode(s: string): string {
  let out = "";
  let i = 0;
  while (i < s.length) {
    const c = s[i] ?? "";
    const next = s[i + 1] ?? "";
    if (c === "/" && next === "/") {
      const eol = s.indexOf("\n", i);
      const end = eol < 0 ? s.length : eol;
      out += " ".repeat(end - i);
      i = end;
    } else if (c === "/" && next === "*") {
      const close = s.indexOf("*/", i + 2);
      const end = close < 0 ? s.length : close + 2;
      out += s.slice(i, end).replace(/[^\n]/gu, " ");
      i = end;
    } else if (c === "'" || c === '"' || c === "`") {
      let j = i + 1;
      while (j < s.length && s[j] !== c) j += s[j] === "\\" ? 2 : 1;
      out += c + s.slice(i + 1, j).replace(/[^\n]/gu, " ") + c;
      i = j + 1;
    } else {
      out += c;
      i += 1;
    }
  }
  return out;
}

const FOCUS_DOT_CALL = /\b(?:it|test|describe|suite)\s*(?:\.\s*[A-Za-z]+\s*)*\.\s*only\b/u;
const FOCUS_BRACKET_CALL = /\b(?:it|test|describe|suite)\s*\[\s*["']only["']\s*\]/u;

/** A focused call anywhere in a pinned file narrows the whole run: a census-level red, independent of allowOnly. */
function auditFocus(source: string): string | undefined {
  return FOCUS_DOT_CALL.test(maskCode(source)) || FOCUS_BRACKET_CALL.test(maskComments(source)) ? "[only-focus] the file carries a focused .only call, which silently narrows every sibling case" : undefined;
}

function escapeRegExp(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/gu, "\\$&");
}

/** The reporter-name matcher for an it.each title: each format specifier matches any substituted text. */
function eachMatcher(title: string): RegExp {
  const body = title
    .split(/%[sjdoif]/u)
    .map(escapeRegExp)
    .join(".+?");
  return new RegExp(`^(?:.* > )?${body}$`, "u");
}

function locateCalls(code: string, title: string): number[] {
  const opens: number[] = [];
  for (const literal of titleLiterals(title)) {
    let from = 0;
    for (;;) {
      const at = code.indexOf(literal, from);
      if (at < 0) break;
      from = at + literal.length;
      const before = code.slice(0, at).trimEnd();
      if (before.endsWith("(")) opens.push(before.length - 1);
    }
  }
  return opens;
}

/** For `it.each(table)(title, fn)`: the index just before ".each(", located by balanced-scanning the table call. */
function eachHeadEnd(code: string, open: number): number | undefined {
  const between = code.slice(0, open).trimEnd();
  if (!between.endsWith(")")) return undefined;
  const close = between.length - 1;
  let from = between.lastIndexOf(".each(", close);
  while (from >= 0) {
    const reached = skipCode(code, from + ".each(".length);
    if (reached === close) return from;
    from = from > 0 ? between.lastIndexOf(".each(", from - 1) : -1;
  }
  return undefined;
}

const ASSERTION_CALL = /\b(?:expect|assert)[A-Za-z]*\s*[.(]/u;

/** Index of the opening "{" that starts a function body inside masked argument text, when it has one. */
function bodyDepthAt(masked: string, upTo: number): number {
  let depth = 0;
  for (let i = 0; i < upTo; i += 1) {
    if (masked[i] === "{") depth += 1;
    else if (masked[i] === "}") depth -= 1;
  }
  return depth;
}

/**
 * Third leg: the located body must be able to assert. Strings and comments are blanked first, so an expect spelled in
 * text never counts. A body with no expect/assert call, or one that returns at its own top level before the first
 * one, is a vacuous pass.
 */
function auditBody(masked: string): string | undefined {
  const first = ASSERTION_CALL.exec(masked);
  if (!first) return "[hollow-body] the pinned case body reaches no expect/assert call, so it can only pass vacuously";
  const prefix = masked.slice(0, first.index);
  for (const match of prefix.matchAll(/\breturn\b/gu)) {
    if (bodyDepthAt(masked, match.index ?? 0) === 1) return "[hollow-body] the pinned case body returns at its top level before its first expect/assert call";
  }
  return undefined;
}

/**
 * Returns a problem string beginning with a [category] tag for one pinned title, or undefined when the reporter lists
 * it exactly once (an it.each pin: its declared instance count) and the located call is a plain, undisabled it()/test()
 * whose body can assert. The call that ENCLOSES the title literal is resolved; there is no last-head fallback.
 * `file` is the real path the reporter prints.
 */
function auditPin(listing: readonly ListedCase[], file: string, source: string, pin: Pick<Pin, "title" | "each" | "instances">): string | undefined {
  const title = pin.title;
  const isEach = pin.each !== undefined;
  const expected = pin.each ?? pin.instances;
  const matcher = eachMatcher(title);
  const listed = listing.filter((entry) => entry.file === file && (isEach ? matcher.test(entry.name) : entry.name === title || entry.name.endsWith(` > ${title}`)));
  if (listed.length === 0) {
    return "[not-registered] the collect-only listing has no such case (renamed, deleted, commented out, skipped, todo'd, parked behind a describe modifier or option, conditionally registered, aliased, shadowed or wrapped in an empty table)";
  }
  if (expected !== undefined) {
    if (listed.length !== expected) return `[each-count] the collect-only listing has ${listed.length} instances, expected exactly ${expected}`;
  } else if (listed.length > 1) return `[duplicate] the collect-only listing has ${listed.length} such cases, expected exactly one`;

  const code = maskComments(source);
  const opens = locateCalls(code, title);
  if (opens.length !== 1) return `[source-unlocated] the title is a call argument ${opens.length} times in the source, expected exactly once`;
  const open = opens[0] ?? 0;
  let head = code.slice(0, open).trimEnd();
  if (isEach) {
    const eachAt = eachHeadEnd(code, open);
    if (eachAt === undefined) return "[call-head] the pinned it.each table call could not be located";
    head = code.slice(0, eachAt).trimEnd();
  } else if (/[)\]]$/u.test(head)) return "[call-head-modifier] the call head is a modifier expression, not a plain it()/test()";
  const headMatch = HEAD_MODIFIER.exec(head);
  if (!headMatch) return "[call-head] the call head is not a plain it()/test() (aliased, shadowed, void-substituted or bracketed binding)";
  const modifiers = (headMatch[1] ?? "")
    .split(".")
    .map((part) => part.trim())
    .filter((part) => part.length > 0);
  const blocked = modifiers.filter((part) => !ALLOWED_HEAD_MODIFIERS.has(part));
  if (blocked.length > 0) return `[call-head-modifier] the call head carries .${blocked.join(".")}`;

  const args = callArguments(code, open);
  if (!args) return "[source-unbalanced] the pinned call could not be scanned to its closing parenthesis";
  for (const arg of args.slice(1)) {
    const text = arg.trim();
    if (text.startsWith("{")) {
      const option = OPTION_MODIFIER.exec(text);
      if (option) return `[options-modifier] the options argument sets ${option[1]}`;
    } else if (RUNTIME_SKIP.test(text)) {
      return "[runtime-skip] the case body calls skip() (a runtime skip the collect-only run cannot see)";
    }
  }
  const bodyArg = [...args].reverse().find((arg) => /=>|\bfunction\b/u.test(arg)) ?? "";
  return auditBody(maskCode(bodyArg));
}

