/** A callee read through its parentheses, non-null assertions, as and satisfies clauses and angle-bracket assertions (THE JUDGE's CALLEE: claimed on V2's wrapped plant only). */
function unwrapped(callee: ts.Expression): ts.Expression {
  let at = callee;
  while (ts.isParenthesizedExpression(at) || ts.isNonNullExpression(at) || ts.isAsExpression(at) || ts.isSatisfiesExpression(at) || ts.isTypeAssertionExpression(at)) at = at.expression;
  return at;
}
function memberNameOf(expression: ts.Expression): string | undefined {
  const callee = unwrapped(expression);
  if (ts.isPropertyAccessExpression(callee)) return callee.name.text;
  if (ts.isElementAccessExpression(callee) && ts.isStringLiteralLike(callee.argumentExpression)) return callee.argumentExpression.text;
  return undefined;
}
type ReachVerdict = "read" | "non-read" | "unknown" | "computed";
/** A module's invoke and inspect member calls, by their literal target or as computed (THE JUDGE's REACH: claimed on V2's plants, and on the real call sites as V1 pins them). */
function reachesOf(source: ts.SourceFile): (string | null)[] {
  const targets: (string | null)[] = [];
  for (const node of nodes(source)) {
    if (!ts.isCallExpression(node)) continue;
    const member = memberNameOf(node.expression);
    if (member !== "invoke" && member !== "inspect") continue;
    const first = node.arguments[0];
    targets.push(first !== undefined && ts.isStringLiteralLike(first) ? first.text : null);
  }
  return targets;
}
function reachVerdictOf(target: string | null, classes: ReadonlyMap<string, readonly string[]>): ReachVerdict {
  if (target === null) return "computed";
  const held = classes.get(target);
  return held === undefined ? "unknown" : held.every(effectClass => effectClass === READ_CLASS) ? "read" : "non-read";
}
interface HandlerVerdict {
  readonly apoModules: readonly string[];
  readonly reaches: { readonly [path: string]: readonly ReachVerdict[] };
  readonly violations: { readonly [path: string]: readonly ReachVerdict[] };
}
/** THE REACH FALSIFIER: an APO module's reaches whose verdict is not read, named by module (claimed on V2's plants and the real modules only). */
function judgeHandlers(entries: readonly Entry[], classes: ReadonlyMap<string, readonly string[]>): HandlerVerdict {
  const apoModules: string[] = [];
  const reaches: { [path: string]: ReachVerdict[] } = {};
  const violations: { [path: string]: ReachVerdict[] } = {};
  for (const item of entries) {
    if (!SCRIPT.test(item.path) || item.bytes.includes(0)) continue;
    const verdicts = reachesOf(sourceOf(item)).map(target => reachVerdictOf(target, classes));
    if (verdicts.length > 0) reaches[item.path] = verdicts;
    if (verdictOf(item, mentions).forms.length === 0) continue;
    apoModules.push(item.path);
    const failing = verdicts.filter(verdict => verdict !== "read");
    if (failing.length > 0) violations[item.path] = failing;
  }
  return { apoModules, reaches, violations };
}
