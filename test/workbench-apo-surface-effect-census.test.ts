/** A module set's register calls: descriptor sites with their enclosing function, and non-literal calls (THE JUDGE's REGISTRATION SITE: claimed on O2's and Q9's plants and the real src/ files only). */
function registrationsOf(entries: readonly Entry[]): { readonly sites: { readonly path: string; readonly enclosing: string | null }[]; readonly nonLiteral: { [path: string]: number } } {
  const sites: { path: string; enclosing: string | null }[] = [];
  const nonLiteral: { [path: string]: number } = {};
  const enclosingName = (node: ts.Node): string | null => {
    for (let at: ts.Node | undefined = node.parent; at !== undefined; at = at.parent) {
      if (ts.isFunctionDeclaration(at) || ts.isMethodDeclaration(at)) return at.name !== undefined && ts.isIdentifier(at.name) ? at.name.text : null;
      if ((ts.isArrowFunction(at) || ts.isFunctionExpression(at)) && ts.isVariableDeclaration(at.parent) && ts.isIdentifier(at.parent.name)) return at.parent.name.text;
    }
    return null;
  };
  for (const item of entries) {
    if (!SCRIPT.test(item.path) || item.bytes.includes(0)) continue;
    for (const node of nodes(sourceOf(item))) {
      if (!ts.isCallExpression(node) || memberNameOf(node.expression) !== "register") continue;
      const argument = node.arguments[0];
      const descriptor =
        argument !== undefined && ts.isObjectLiteralExpression(argument)
          ? argument.properties.find(property => ts.isPropertyAssignment(property) && ts.isIdentifier(property.name) && property.name.text === "descriptor")
          : undefined;
      if (descriptor !== undefined) sites.push({ path: item.path, enclosing: enclosingName(node) });
      else nonLiteral[item.path] = (nonLiteral[item.path] ?? 0) + 1;
    }
  }
  return { sites, nonLiteral };
}
/** The exported function declarations of the provider modules whose name begins "register", with their module (THE JUDGE's REGISTRARS: claimed on the real providers and O2's registrar plants only). */
function exportedRegistrars(entries: readonly Entry[]): { readonly path: string; readonly name: string }[] {
  const found: { path: string; name: string }[] = [];
  for (const item of entries) {
    if (!item.path.startsWith(PROVIDERS) || !SCRIPT.test(item.path)) continue;
    for (const statement of sourceOf(item).statements) {
      if (!ts.isFunctionDeclaration(statement) || statement.name === undefined || !/^register/.test(statement.name.text)) continue;
      if (statement.modifiers?.some(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword) === true) found.push({ path: item.path, name: statement.name.text });
    }
  }
  return found;
}
/** The final names of the calls inside registerNativeProviders's body, in order. */
function nativeComposition(): string[] {
  const source = parse(NATIVE_MODULES, textOf(NATIVE_MODULES));
  const method = nodes(source).find((node): node is ts.MethodDeclaration => ts.isMethodDeclaration(node) && ts.isIdentifier(node.name) && node.name.text === NATIVE_SURFACE && node.body !== undefined);
  if (method?.body === undefined) return [];
  return nodes(method.body)
    .filter((node): node is ts.CallExpression => ts.isCallExpression(node))
    .map(call => memberNameOf(call.expression) ?? (ts.isIdentifier(call.expression) ? call.expression.text : "?"));
}
/** The registry's own effect vocabulary: the EFFECT_CLASSES literal and the CapabilityDescriptor effectClass union. */
function registryVocabulary(): { readonly vocabulary: string[]; readonly unionMembers: string[] } {
  let vocabulary: string[] = [];
  let unionMembers: string[] = [];
  for (const node of nodes(parse(REGISTRY_SOURCE, textOf(REGISTRY_SOURCE)))) {
    if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name) && node.name.text === "EFFECT_CLASSES" && node.initializer !== undefined) {
      const array = ts.isCallExpression(node.initializer) ? node.initializer.arguments[0] : node.initializer;
      if (array !== undefined && ts.isArrayLiteralExpression(array)) vocabulary = array.elements.filter(ts.isStringLiteralLike).map(element => element.text);
    }
    if (ts.isInterfaceDeclaration(node) && node.name.text === "CapabilityDescriptor") {
      for (const member of node.members) {
        if (!ts.isPropertySignature(member) || !ts.isIdentifier(member.name) || member.name.text !== "effectClass" || member.type === undefined || !ts.isUnionTypeNode(member.type)) continue;
        unionMembers = member.type.types
          .filter(ts.isLiteralTypeNode)
          .map(type => type.literal)
          .filter(ts.isStringLiteral)
          .map(literal => literal.text);
      }
    }
  }
  return { vocabulary, unionMembers };
}

