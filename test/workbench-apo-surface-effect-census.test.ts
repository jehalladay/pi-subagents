/** The quotes tile the text in order, with nothing but separators between them (and after the last). */
function tiles(text: string, quotes: readonly string[], separators: RegExp = /^[\s,;:.()]*$/): boolean {
  let at = 0;
  for (const quote of quotes) {
    const found = text.indexOf(quote, at);
    if (quote === "" || found < 0 || !separators.test(text.slice(at, found))) return false;
    at = found + quote.length;
  }
  return separators.test(text.slice(at));
}

/** A text's words: its letter-or-digit runs, split again at a case change or a letter-digit boundary, lower-cased. */
function wordsOf(text: string): string[] {
  const words: string[] = [];
  for (const run of text.match(/[\p{L}\p{N}]+/gu) ?? []) {
    for (const word of run.match(/\p{Lu}{2,}(?=s(?!\p{Ll}))|\p{Lu}+(?!\p{Ll})|\p{Lu}\p{Ll}*|\p{Ll}+|\p{N}+|[^\p{Lu}\p{Ll}\p{N}]+/gu) ?? []) {
      words.push(word.toLowerCase());
    }
  }
  return words;
}
/** A slug word's stem: singular or plural, s or z where the word has a z, y or ies where it ends in y. */
function stemPattern(word: string): string {
  const singular = word.replace(/s$/, "").replace(/z/g, "[sz]");
  return singular.endsWith("y") ? `${singular.slice(0, -1)}(?:y|ies)` : `${singular}s?`;
}
const STEMS: readonly RegExp[] = PROGRAM_SLUG.split("-").map(word => new RegExp(`^${stemPattern(word)}$`));
const ABBREVIATION_WORD = ABBREVIATION.toLowerCase();
type Matcher = (text: string) => boolean;
/** THE JUDGE: the abbreviation's word, or the slug's words in order by their stems. */
const mentions: Matcher = text => {
  const words = wordsOf(text);
  return words.some((word, at) => word === ABBREVIATION_WORD || STEMS.every((stem, offset) => stem.test(words[at + offset] ?? "")));
};
/** A matcher for one phrase's words in order (the content-liveness anchor reads a registered capability id with it). */
function phraseMatcher(phrase: string): Matcher {
  const target = wordsOf(phrase);
  return text => {
    const words = wordsOf(text);
    return words.some((_, at) => target.every((word, offset) => words[at + offset] === word));
  };
}

type Form = "path" | "raw" | "cooked" | "folded";
interface Entry {
  readonly path: string;
  readonly bytes: Buffer;
}
interface ScopeVerdict {
  readonly files: number;
  readonly scripts: number;
  readonly binaries: readonly string[];
  readonly findings: { readonly [path: string]: readonly Form[] };
}
function entry(path: string, text: string): Entry {
  return { path, bytes: Buffer.from(text, "utf8") };
}
function parse(path: string, text: string): ts.SourceFile {
  const kind = /x$/.test(path) ? ts.ScriptKind.TSX : /\.[cm]?js$/.test(path) ? ts.ScriptKind.JS : ts.ScriptKind.TS;
  return ts.createSourceFile(path, text, ts.ScriptTarget.Latest, true, kind);
}
function nodes(root: ts.Node): ts.Node[] {
  const found: ts.Node[] = [];
  const visit = (node: ts.Node): void => {
    found.push(node);
    ts.forEachChild(node, visit);
  };
  visit(root);
  return found;
}
/** A script's cooked and folded units: each string-like literal, each template part, each all-literal "+" chain. */
function scriptUnits(source: ts.SourceFile): { readonly form: Form; readonly text: string }[] {
  const units: { form: Form; text: string }[] = [];
  const isPlus = (node: ts.Node): node is ts.BinaryExpression => ts.isBinaryExpression(node) && node.operatorToken.kind === ts.SyntaxKind.PlusToken;
  const folded = (node: ts.Expression): string | undefined => {
    if (ts.isStringLiteralLike(node)) return node.text;
    if (ts.isParenthesizedExpression(node)) return folded(node.expression);
    if (isPlus(node)) {
      const left = folded(node.left);
      const right = folded(node.right);
      return left === undefined || right === undefined ? undefined : left + right;
    }
    return undefined;
  };
  for (const node of nodes(source)) {
    if (ts.isStringLiteralLike(node)) units.push({ form: "cooked", text: node.text });
    else if (ts.isTemplateExpression(node)) {
      units.push({ form: "cooked", text: node.head.text });
      for (const span of node.templateSpans) units.push({ form: "cooked", text: span.literal.text });
    } else if (isPlus(node) && !isPlus(node.parent)) {
      const value = folded(node);
      if (value !== undefined) units.push({ form: "folded", text: value });
    }
  }
  return units;
}
const PARSED = new Map<string, ts.SourceFile>();
/** A script entry's AST, parsed once per path and bytes. */
function sourceOf(item: Entry): ts.SourceFile {
  const key = `${item.path}\0${createHash("sha256").update(item.bytes).digest("hex")}`;
  const held = PARSED.get(key);
  if (held !== undefined) return held;
  const source = parse(item.path, item.bytes.toString("utf8"));
  PARSED.set(key, source);
  return source;
}
/** One file's verdict under a matcher: binary (a NUL byte, not read) or the sorted forms in which the matcher read it. */
function verdictOf(item: Entry, matcher: Matcher): { readonly binary: boolean; readonly forms: readonly Form[] } {
  const forms = new Set<Form>();
  if (matcher(item.path)) forms.add("path");
  if (item.bytes.includes(0)) return { binary: true, forms: [...forms].sort() };
  if (matcher(item.bytes.toString("utf8"))) forms.add("raw");
  if (SCRIPT.test(item.path)) for (const unit of scriptUnits(sourceOf(item))) if (matcher(unit.text)) forms.add(unit.form);
  return { binary: false, forms: [...forms].sort() };
}
/** Judges an entry list in one call: the real entries first, then any planted ones. */
function judgeScope(entries: Iterable<Entry>, matcher: Matcher = mentions): ScopeVerdict {
  let files = 0;
  let scripts = 0;
  const binaries: string[] = [];
  const findings: { [path: string]: Form[] } = {};
  for (const item of entries) {
    files += 1;
    const verdict = verdictOf(item, matcher);
    if (verdict.forms.length > 0) findings[item.path] = [...verdict.forms];
    if (verdict.binary) {
      binaries.push(item.path);
      continue;
    }
    if (SCRIPT.test(item.path)) scripts += 1;
  }
  return { files, scripts, binaries, findings };
}
function findingsFor(verdict: ScopeVerdict, paths: readonly string[], within: boolean): { [path: string]: Form[] } {
  return Object.fromEntries(Object.entries(verdict.findings).filter(([path]) => paths.includes(path) === within).map(([path, forms]) => [path, [...forms]]));
}

