interface Presentation {
  readonly entries: readonly Entry[];
  readonly record: (inner: Matcher) => Matcher;
  readonly presented: ReadonlyMap<string, readonly string[]>;
}
/** A presentation record: entries wrapped so that a reader's own read of an entry's path or bytes makes that entry the owner of every text the recording matcher is handed next. */
function presentation(entries: readonly Entry[]): Presentation {
  const presented = new Map<string, string[]>();
  let owner = "";
  const wrapped = entries.map(
    (item): Entry => ({
      get path(): string {
        owner = item.path;
        return item.path;
      },
      get bytes(): Buffer {
        owner = item.path;
        return item.bytes;
      },
    }),
  );
  const record =
    (inner: Matcher): Matcher =>
    text => {
      const held = presented.get(owner);
      if (held === undefined) presented.set(owner, [text]);
      else held.push(text);
      return inner(text);
    };
  return { entries: wrapped, record, presented };
}
