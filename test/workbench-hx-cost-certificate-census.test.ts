/** Every statement reading the `coverage` member (property, literal element access or destructuring), the bindings those statements
 * declare, the map callbacks consuming a binding and each member a callback reads from its parameter (directly or through one call). */
function coverageRead(text: string): CoverageRead {
  const file = ts.createSourceFile('module.ts', text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  const statements = new Set<ts.Node>();
  const member = (node: ts.Node): string | undefined => {
    if (ts.isPropertyAccessExpression(node)) return node.name.text;
    if (ts.isElementAccessExpression(node) && ts.isStringLiteralLike(node.argumentExpression)) return node.argumentExpression.text;
    if (ts.isBindingElement(node)) {
      const key = node.propertyName ?? node.name;
      return ts.isIdentifier(key) || ts.isStringLiteralLike(key) ? key.text : undefined;
    }
    return undefined;
  };
  const statementOf = (node: ts.Node): ts.Node => {
    let at = node;
    while (!ts.isBlock(at.parent) && !ts.isSourceFile(at.parent)) at = at.parent;
    return at;
  };
  const findReads = (node: ts.Node): void => {
    if (member(node) === 'coverage') statements.add(statementOf(node));
    ts.forEachChild(node, findReads);
  };
  findReads(file);
  const bindings = [...statements].flatMap(statement => ts.isVariableStatement(statement)
    ? statement.declarationList.declarations.flatMap(declaration => ts.isIdentifier(declaration.name) ? [declaration.name] : []) : []);
  const reads = new Set<string>();
  let callbacks = 0;
  let escapes = 0;
  const references = (root: ts.Node, name: string, declared: ts.Node): ts.Identifier[] => {
    const found: ts.Identifier[] = [];
    const visit = (node: ts.Node): void => {
      if (ts.isIdentifier(node) && node.text === name && node !== declared) found.push(node);
      ts.forEachChild(node, visit);
    };
    visit(root);
    return found;
  };
  for (const binding of bindings) {
    for (const reference of references(file, binding.text, binding)) {
      const access = reference.parent;
      const call = access.parent;
      const callback = ts.isCallExpression(call) ? call.arguments[0] : undefined;
      if (!ts.isPropertyAccessExpression(access) || access.expression !== reference || access.name.text !== 'map' || !ts.isCallExpression(call) ||
        call.expression !== access || callback === undefined || !(ts.isArrowFunction(callback) || ts.isFunctionExpression(callback))) {
        escapes++;
        continue;
      }
      callbacks++;
      const parameter = callback.parameters[0]?.name;
      if (parameter === undefined || !ts.isIdentifier(parameter)) {
        escapes++;
        continue;
      }
      for (const use of references(callback.body, parameter.text, parameter)) {
        const parent = use.parent;
        if (ts.isPropertyAccessExpression(parent) && parent.expression === use) reads.add(parent.name.text);
        else if (ts.isElementAccessExpression(parent) && parent.expression === use && ts.isStringLiteralLike(parent.argumentExpression)) reads.add(parent.argumentExpression.text);
        else if (ts.isCallExpression(parent) && ts.isPropertyAccessExpression(parent.parent) && parent.parent.expression === parent) reads.add(parent.parent.name.text);
        else escapes++;
      }
    }
  }
  return {statements: statements.size, callbacks, reads: [...reads].sort(), escapes};
}
