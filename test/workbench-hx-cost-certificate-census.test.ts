/** Clause (b)'s two unknown-field names and the TI id it names. */
function unknownFields(): {keys: string[]; refs: string[]} {
  const [field = '', list = '', ref = ''] = derived(/^\(b\) today: (\S+) and (\S+) \['([^']+)'\] as unknown fields/, clauses()[1] ?? '');
  return {keys: [field, list], refs: [ref]};
}
/** A pattern's literal heads: the prefix before its group joined to each alternative's leading literal run. */
function patternHeads(pattern: string): string[] {
  const [prefix = '', group = ''] = derived(/^\^([^(]*)\((.+)\)\$$/, pattern);
  return group.split('|').map(alternative => prefix + (/^[^[.(\\{+*?]*/.exec(alternative)?.[0] ?? '')).sort();
}
function tiled(body: string, quotes: readonly string[]): boolean {
  let at = 0;
  for (const quote of quotes) {
    const found = body.indexOf(quote, at);
    if (found < 0 || !/^[\s,;:]*$/.test(body.slice(at, found))) return false;
    at = found + quote.length;
  }
  return /^[\s,;:]*$/.test(body.slice(at));
}

