function asciiOnly(text: string): boolean {
  for (let index = 0; index < text.length; index += 1) if (text.charCodeAt(index) > 127) return false;
  return true;
}
/** NFKC, lower case, format characters dropped: the whole-text quick reject and the per-line quick test. */
const quickFold = (text: string): string => (asciiOnly(text) ? text.toLowerCase() : text.replace(/\p{Cf}/gu, "").normalize("NFKC").toLowerCase());
/** Per-character fold of one line with the raw index of every folded unit, so a reading recovers its exact source characters. */
function fold(line: string): { readonly folded: string; readonly at: readonly number[] } {
  let folded = "";
  const at: number[] = [];
  let index = 0;
  for (const char of line) {
    if (char.charCodeAt(0) < 128) {
      folded += char.toLowerCase();
      at.push(index);
    } else if (!FORMAT.test(char)) {
      const unit = char.normalize("NFKC").toLowerCase();
      folded += unit;
      for (let k = 0; k < unit.length; k += 1) at.push(index);
    }
    index += char.length;
  }
  return { folded, at };
}
/** Every family reading of `text`, line by line; `fixedLine` stamps cooked and decoded readings with their node's line. */
function readText(path: string, text: string, layer: Layer, fixedLine?: number): Reading[] {
  if (!FAMILY_ANY.test(quickFold(text))) return [];
  const readings: Reading[] = [];
  let lineNumber = 0;
  for (const line of text.split("\n")) {
    lineNumber += 1;
    const ascii = asciiOnly(line);
    const quick = ascii ? line.toLowerCase() : quickFold(line);
    if (!FAMILY_ANY.test(quick)) continue;
    const { folded, at } = ascii ? { folded: quick, at: null } : fold(line);
    for (const match of folded.matchAll(FAMILY)) {
      const [whole, ns = "", gap = "", family = "", major, tail = ""] = match;
      const namespace: Namespace = ns === "decision" ? "decision" : ns === "graph" ? "graph" : "graphpolicy";
      if ((namespace === "decision") !== (family === "factor")) continue;
      if (major === undefined && namespace !== "decision") continue; // R-NAMESPACE-ONLY: a namespace without a major is no id
      if (major === undefined && /^\s+$/.test(gap)) continue; // "decision factor" in prose names no id
      const start = match.index;
      const last = start + whole.length - 1;
      const rawStart = at === null ? start : (at[start] ?? 0);
      const rawLast = at === null ? last : (at[last] ?? 0);
      const rawEnd = rawLast + ((line.codePointAt(rawLast) ?? 0) > 0xffff ? 2 : 1);
      readings.push({ path, line: fixedLine ?? lineNumber, layer, namespace, family: family as Family, major: major === undefined ? null : `${major}${tail}`, raw: line.slice(rawStart, rawEnd) });
    }
  }
  return readings;
}
const key = (reading: Reading): string => `${reading.namespace}|${reading.family}|${reading.major}|${reading.raw}`;
/** The readings of `cooked` that `source` does not already hold (multiset difference by key). */
function beyond(path: string, cooked: string, source: string, layer: Layer, line: number): Reading[] {
  const held = new Map<string, number>();
  for (const reading of readText(path, source, layer, line)) held.set(key(reading), (held.get(key(reading)) ?? 0) + 1);
  return readText(path, cooked, layer, line).filter(reading => {
    const left = held.get(key(reading)) ?? 0;
    held.set(key(reading), left - 1);
    return left <= 0;
  });
}
function constant(node: ts.Node): string | undefined {
  if (ts.isStringLiteralLike(node)) return node.text;
  if (ts.isParenthesizedExpression(node)) return constant(node.expression);
  if (ts.isBinaryExpression(node) && node.operatorToken.kind === ts.SyntaxKind.PlusToken) {
    const left = constant(node.left);
    const right = constant(node.right);
    return left === undefined || right === undefined ? undefined : left + right;
  }
  if (ts.isTemplateExpression(node)) {
    let text = node.head.text;
    for (const span of node.templateSpans) {
      const value = constant(span.expression);
      if (value === undefined) return undefined;
      text += value + span.literal.text;
    }
    return text;
  }
  return undefined;
}
function scriptKind(path: string): ts.ScriptKind {
  return /\.[cm]?js$/.test(path) ? ts.ScriptKind.JS : /\.jsx$/.test(path) ? ts.ScriptKind.JSX : /\.tsx$/.test(path) ? ts.ScriptKind.TSX : ts.ScriptKind.TS;
}
/** Readings the compiler cooks beyond the raw text: each maximal constant string expression, read past its own source span. */
function cooked(path: string, text: string): Reading[] {
  const source = ts.createSourceFile(path, text, ts.ScriptTarget.Latest, true, scriptKind(path));
  const readings: Reading[] = [];
  const visit = (node: ts.Node): void => {
    const value = ts.isStringLiteralLike(node) || ts.isBinaryExpression(node) || ts.isTemplateExpression(node) || ts.isParenthesizedExpression(node) ? constant(node) : undefined;
    if (value !== undefined) {
      const line = source.getLineAndCharacterOfPosition(node.getStart(source)).line + 1;
      readings.push(...beyond(path, value, node.getText(source), "cooked", line));
      return;
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
  return readings;
}
function strings(value: unknown): string[] {
  if (typeof value === "string") return [value];
  if (Array.isArray(value)) return value.flatMap(strings);
  return value !== null && typeof value === "object" ? Object.entries(value).flatMap(([name, item]) => [name, ...strings(item)]) : [];
}
