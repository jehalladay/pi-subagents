/** G-SWAPW guard: the labels whose finding codes share no word with the pin's bead quote (codes are kebab words). */
function codesOffQuote(quote: string, witness: Json): string[] {
  const words = new Set(expand(quote).toLowerCase().split(/[\s,()-]+/));
  const misses: string[] = [];
  const visit = (value: Json): void => {
    if (value === null || typeof value !== "object") return;
    if (!Array.isArray(value)) {
      for (const item of Object.values(value)) visit(item);
      return;
    }
    const entries: readonly Json[] = value;
    const [label, codes] = entries;
    if (entries.length === 2 && typeof label === "string" && Array.isArray(codes)) {
      const list: readonly Json[] = codes;
      const kebab = list.filter((code): code is string => typeof code === "string" && /^[a-z]+(?:-[a-z]+)+$/.test(code));
      if (kebab.length === list.length) {
        if (kebab.length > 0 && !kebab.some(code => code.split("-").some(word => words.has(word)))) misses.push(label);
        return;
      }
    }
    for (const item of entries) visit(item);
  };
  visit(witness);
  return misses;
}

