/** git's would-commit listing under the pathspecs (tracked and untracked, never ignored), each a regular file on disk, sorted. */
function listing(cwd: string, pathspecs: readonly string[]): string[] {
  const listed = execFileSync("git", ["ls-files", "-z", "--cached", "--others", "--exclude-standard", "--", ...pathspecs], { cwd, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
  return [...new Set(listed.split("\0").filter(path => path !== "" && existsSync(join(cwd, path)) && statSync(join(cwd, path)).isFile()))].sort();
}
const walked = new Map<Root, readonly Entry[]>();
function walk(root: Root): readonly Entry[] {
  note(root);
  const cached = walked.get(root);
  if (cached !== undefined) return cached;
  const entries = listing(ROOT, PATHSPECS[root]).map(path => {
    const bytes = readFileSync(join(ROOT, path));
    return { path, text: bytes.includes(0) ? BINARY : bytes.toString("utf8") };
  });
  walked.set(root, entries);
  return entries;
}
function liveness(root: Root): { readonly floor: boolean; readonly anchor: boolean } {
  const entries = walk(root);
  const anchor = ANCHORS[root].every(({ path, token }) => entries.find(entry => entry.path === path)?.text.includes(token) === true);
  return { floor: entries.length >= FLOORS[root], anchor };
}
const excluded = (path: string): boolean => EXCLUDED.some(prefix => path.startsWith(prefix));
/** The root a path falls under, as PATHSPECS partitions the tree (none under an exclusion). */
function rootOf(path: string): Root | undefined {
  if (excluded(path)) return undefined;
  const dir = PRODUCT_DIRS.find(name => path.startsWith(`${name}/`));
  if (dir !== undefined) return dir;
  if (!path.endsWith(".md")) return "config";
  return path.includes("/") ? "other-md" : "front";
}
/** The tree's own listing against the walks: every file outside the exclusions is walked by exactly one root, the root its path names. */
function closure(): { readonly unwalked: string[]; readonly doubled: string[]; readonly excludedWalked: string[]; readonly misrouted: string[] } {
  note("closure");
  const owners = new Map<string, Root[]>();
  for (const root of ROOTS) for (const entry of walk(root)) owners.set(entry.path, [...(owners.get(entry.path) ?? []), root]);
  return {
    unwalked: listing(ROOT, ["."]).filter(path => !excluded(path) && !owners.has(path)),
    doubled: [...owners].filter(([, roots]) => roots.length > 1).map(([path]) => path),
    excludedWalked: [...owners.keys()].filter(excluded),
    misrouted: [...owners].filter(([path, roots]) => rootOf(path) !== roots[0]).map(([path]) => path),
  };
}
