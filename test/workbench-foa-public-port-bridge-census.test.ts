/** The export's field schema: every field any row carries (the id aside), each with its first sample that holds a string. */
function exportSchema(rows: readonly ExportRow[]): Map<string, Json> {
  const schema = new Map<string, Json>();
  for (const row of rows) {
    for (const [field, value] of Object.entries(row.fields)) {
      const known = schema.get(field);
      if (field !== "id" && (known === undefined || (!hasString(known) && hasString(value)))) schema.set(field, value);
    }
  }
  return schema;
}
