/** The script extensions: TypeScript's own extension table (ts.Extension) less its two data members, by file extension (the outside anchor below). */
const CODE_EXTENSIONS = new Set([".ts", ".mts", ".cts", ".tsx", ".js", ".mjs", ".cjs", ".jsx"]);
const MARKUP_EXTENSIONS = new Set([".md", ".html", ".htm", ".xml", ".svg"]);
const DATA_EXTENSIONS: readonly string[] = [ts.Extension.Json, ts.Extension.TsBuildInfo];
/** Every extension TypeScript's own table names, less its data members, reduced to the file extension a path carries. */
const tsScriptExtensions = (): string[] => [...new Set(Object.values(ts.Extension).filter(extension => !DATA_EXTENSIONS.includes(extension)).map(extension => extname(`x${extension}`)))];
function scriptKindOf(path: string): ts.ScriptKind {
  const extension = extname(path).toLowerCase();
  if (extension === ".tsx") return ts.ScriptKind.TSX;
  if (extension === ".jsx") return ts.ScriptKind.JSX;
  if (extension === ".js" || extension === ".mjs" || extension === ".cjs") return ts.ScriptKind.JS;
  return ts.ScriptKind.TS;
}
/** Each string-like literal and template part by its cooked value, each escaped identifier or private name by its cooked name, each "+" chain of string literals folded. */
function cookedParts(path: string, text: string): string[] {
  const source = ts.createSourceFile(path, text, ts.ScriptTarget.Latest, true, scriptKindOf(path));
  const parts: string[] = [];
  const isPlus = (node: ts.Node): node is ts.BinaryExpression => ts.isBinaryExpression(node) && node.operatorToken.kind === ts.SyntaxKind.PlusToken;
  const fold = (node: ts.Node): string | undefined => {
    if (ts.isStringLiteralLike(node)) return node.text;
    if (ts.isParenthesizedExpression(node)) return fold(node.expression);
    if (!isPlus(node)) return undefined;
    const left = fold(node.left);
    const right = fold(node.right);
    return left === undefined || right === undefined ? undefined : left + right;
  };
  const visit = (node: ts.Node): void => {
    if (ts.isStringLiteralLike(node) || ts.isTemplateHead(node) || ts.isTemplateMiddle(node) || ts.isTemplateTail(node)) parts.push(node.text);
    else if ((ts.isIdentifier(node) || ts.isPrivateIdentifier(node)) && node.getText(source) !== ts.idText(node)) parts.push(ts.idText(node));
    if (isPlus(node) && !isPlus(node.parent)) {
      const folded = fold(node);
      if (folded !== undefined) parts.push(folded);
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
  return parts;
}
/** Each parsed key and string value of a JSON text (none when it does not parse). */
function jsonParts(text: string): string[] {
  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch {
    return [];
  }
  const parts: string[] = [];
  const visit = (value: unknown): void => {
    if (typeof value === "string") parts.push(value);
    else if (Array.isArray(value)) for (const item of value) visit(item);
    else if (record(value)) {
      for (const [key, item] of Object.entries(value)) {
        parts.push(key);
        visit(item);
      }
    }
  };
  visit(parsed);
  return parts;
}
const NAMED_ENTITIES: Readonly<Record<string, string>> = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " " };
/** A numeric character reference (decimal or hex) or a named entity, its closing semicolon optional (HTML5 decodes "&#80" and "&amp" without one). */
const REFERENCE = new RegExp(`&(?:#[xX]([0-9a-fA-F]+)|#([0-9]+)|(${Object.keys(NAMED_ENTITIES).join("|")}));?`, "gi");
/** A markup text with its numeric character references and the common named entities decoded. */
function decoded(text: string): string {
  return text.replace(REFERENCE, (whole: string, hex: string | undefined, decimal: string | undefined, name: string | undefined) => {
    const point = hex !== undefined ? Number.parseInt(hex, 16) : decimal !== undefined ? Number.parseInt(decimal, 10) : undefined;
    if (point !== undefined) return point <= 0x10ffff ? String.fromCodePoint(point) : whole;
    return NAMED_ENTITIES[(name ?? "").toLowerCase()] ?? whole;
  });
}
/** A markup text as it renders: its comments and tags removed (an unclosed comment runs to the end). */
const rendered = (text: string): string => text.replace(/<!--[\s\S]*?(?:-->|$)/g, "").replace(/<[^<>]*>/g, "");
/** A file holding a NUL byte is binary: its path is its only reading. */
const BINARY = "\0";
const readingsCache = new Map<string, readonly string[]>();
/** A file's readings: its path, its raw text, then the cooked, parsed, decoded or rendered readings its extension carries, each also NFKD-decomposed with its marks dropped. */
function readingsOf(path: string, text: string): readonly string[] {
  const key = `${path}\0${text}`;
  const cached = readingsCache.get(key);
  if (cached !== undefined) return cached;
  const extension = extname(path).toLowerCase();
  const readings = [path];
  if (!text.includes(BINARY)) {
    readings.push(text);
    if (CODE_EXTENSIONS.has(extension)) {
      readings.push(...cookedParts(path, text));
      const kind = scriptKindOf(path);
      if (kind === ts.ScriptKind.TSX || kind === ts.ScriptKind.JSX) readings.push(decoded(text));
    } else if (extension === ".json") readings.push(...jsonParts(text));
    else if (MARKUP_EXTENSIONS.has(extension)) readings.push(decoded(text), decoded(rendered(text)));
  }
  const normalized = readings.map(reading => reading.normalize("NFKD").replace(/\p{M}/gu, "")).filter((reading, index) => reading !== readings[index]);
  readings.push(...normalized);
  readingsCache.set(key, readings);
  return readings;
}
/** The judges that fire on a file: any of its readings carries the mention. */
function mentionsIn(path: string, text: string, judges: readonly Judge[]): Judge[] {
  note("mention-judge");
  const readings = readingsOf(path, text);
  return judges.filter(judge => readings.some(reading => JUDGES[judge].test(reading)));
}
/** The claim families a file spells in any reading. */
function claimsIn(path: string, text: string): Family[] {
  note("claim-judge");
  const readings = readingsOf(path, text);
  return FAMILIES.filter(family => readings.some(reading => CLAIMS[family].test(reading)));
}
/** The claim families a rendered label spells. */
function claimsOfLabel(label: string): Family[] {
  note("claim-judge");
  return FAMILIES.filter(family => CLAIMS[family].test(label));
}

