interface ExportRow {
  readonly id: string;
  /** The beads this row is a parent-child child of. */
  readonly parents: readonly string[];
  /** Every field of the row, as the tracker exported it. */
  readonly fields: JsonRecord;
}
function parseExport(text: string): ExportRow[] {
  const rows: ExportRow[] = [];
  for (const line of text.split("\n")) {
    if (line.trim() === "") continue;
    const row = JSON.parse(line) as Json;
    if (!jsonRecord(row) || typeof row.id !== "string") continue;
    const edges = jsonList(row.dependencies) ? row.dependencies.filter(jsonRecord) : [];
    const parents = edges.filter(edge => edge.type === "parent-child" && typeof edge.depends_on_id === "string").map(edge => String(edge.depends_on_id));
    rows.push({ id: row.id, parents, fields: row });
  }
  return rows;
}
