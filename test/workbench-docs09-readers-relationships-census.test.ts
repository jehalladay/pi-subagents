/* Pin-flip probe over registered case names (never over file text)     */
/* ------------------------------------------------------------------ */

/**
 * An unpinned half stays unpinned only while no REGISTERED case (collect-only listing of the whole suite, this file
 * excluded) matches its probe. A comment or string quoting the docs sentence is not a registered case.
 */
function auditUnpinned(half: Half, flipListing: readonly ListedCase[] | undefined, selfFile: string): string | undefined {
  if (!half.flipProbe) return "[pin-flip] an unpinned half carries no pin-flip probe";
  if (flipListing === undefined || flipListing.length === 0) return "[listing-failed] the whole-suite collect-only listing is unavailable, so the pin-flip probe cannot run";
  const hit = flipListing.find((entry) => entry.file !== selfFile && half.flipProbe?.test(entry.name));
  return hit ? `[pin-flip] a registered case now matches the probe (${hit.name} in ${hit.file}); pin it and drop the unpinned reason` : undefined;
}

/* ------------------------------------------------------------------ */
/* Row audit (every failure names the row and half)                     */
/* ------------------------------------------------------------------ */

interface PinLocation {
  readonly absolute: string;
  readonly source: string;
}

/** Violations of one row, each beginning with `<row id>/<half id>`. Empty only when every pin is live and honest. */
function rowViolations(row: Row, listing: readonly ListedCase[], locate: (file: string) => PinLocation, gateConfig: GateConfig, flipListing: readonly ListedCase[] | undefined, selfFile: string): string[] {
  const out: string[] = [];
  for (const half of row.halves) {
    const where = `${row.id}/${half.id}`;
    if (!row.clause.includes(half.clause)) out.push(`${where}: clause is not part of the row clause`);
    if (half.pins.length === 0) {
      if ((half.reason ?? "").trim().length < 60) out.push(`${where}: unpinned half carries no reason`);
      else if (!/wb-[0-9a-z]+(?:\.[0-9]+)?/u.test(half.reason ?? "")) out.push(`${where}: unpinned half names no owning bead`);
      const flip = auditUnpinned(half, flipListing, selfFile);
      if (flip) out.push(`${where}: ${flip}`);
      continue;
    }
    if (half.reason !== undefined || half.flipProbe !== undefined) out.push(`${where}: carries both pins and an unpinned reason or probe`);
    const token = (half.token ?? "").toLowerCase();
    if (token.length === 0) out.push(`${where}: [evidence-token] a pinned half names no evidence token`);
    else if (!half.pins.some((entry) => entry.title.toLowerCase().includes(token))) out.push(`${where}: [evidence-token] no pinned title contains the evidence token "${half.token}", so the clause is not evidenced by any title`);
    for (const entry of half.pins) {
      if (!entry.file.startsWith("test/")) out.push(`${where}: ${entry.file} is not under test/`);
      const tier = auditGateTier(entry.file, gateConfig);
      if (tier) out.push(`${where}: ${entry.file} :: ${entry.title}: ${tier}`);
      const location = locate(entry.file);
      const focus = auditFocus(location.source);
      if (focus) out.push(`${where}: ${entry.file}: ${focus}`);
      const problem = auditPin(listing, location.absolute, location.source, entry);
      if (problem) out.push(`${where}: ${entry.file} :: ${entry.title}: ${problem}`);
    }
  }
  return out;
}

