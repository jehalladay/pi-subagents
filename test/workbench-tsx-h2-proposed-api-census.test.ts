function objectOf(value: unknown, field: string): { [key: string]: unknown } {
  if (!isObject(value)) throw new Error(`roster ${field} must be an object`);
  return value;
}
/** Refuses an object whose keys differ from `keys`, so a re-measure written under a renamed key never reads as absent. */
function exactKeys(value: { [key: string]: unknown }, keys: readonly string[], field: string): void {
  const found = Object.keys(value).sort();
  if (JSON.stringify(found) !== JSON.stringify([...keys].sort())) throw new Error(`roster ${field} keys must be exactly ${keys.join(", ")}; found ${found.join(", ")}`);
}

/** Parses the roster, refusing any field of the wrong shape by name, so no case can read a malformed roster. */
function readRoster(): Roster {
  const raw = objectOf(JSON.parse(readFileSync(join(REPO, ROSTER_FILE), "utf8")), "root");
  exactKeys(raw, ["bead", "quote", "citation", "constants", "producer", "rows", "tests"], "root");
  if (!Array.isArray(raw.rows)) throw new Error("roster rows must be a list");
  const rows = raw.rows.map((row: unknown, index: number): RosterRow => {
    if (!isObject(row) || typeof row.id !== "string" || typeof row.label !== "string" || !Array.isArray(row.pins)) throw new Error(`roster rows[${index}] needs an id, a label and pins`);
    const pins = row.pins.map((pin: unknown, at: number): RosterPin => {
      if (!isObject(pin) || typeof pin.id !== "string" || !Object.hasOwn(pin, "witness")) throw new Error(`roster rows[${index}].pins[${at}] needs an id and a witness`);
      return { id: pin.id, witness: json(pin.witness) };
    });
    return { id: row.id, label: row.label, pins };
  });
  const producer = objectOf(raw.producer, "producer");
  exactKeys(producer, ["installedRf", "rfSource", "sites"], "producer");
  const rf = objectOf(producer.installedRf, "producer.installedRf");
  exactKeys(rf, ["command", "version", "commit", "leaves", "unserved"], "producer.installedRf");
  if (!Array.isArray(producer.rfSource) || !Array.isArray(producer.sites)) throw new Error("roster producer.rfSource and producer.sites must be lists");
  const rfSource = producer.rfSource.map((entry: unknown, index: number): RfSource => {
    const source = objectOf(entry, `producer.rfSource[${index}]`);
    exactKeys(source, ["sha", "command", "srcFiles", "federatedFiles", "stemFiles"], `producer.rfSource[${index}]`);
    return {
      sha: text(source.sha, "sha"),
      command: text(source.command, "command"),
      srcFiles: count(source.srcFiles, "srcFiles"),
      federatedFiles: strings(source.federatedFiles, "federatedFiles"),
      stemFiles: strings(source.stemFiles, "stemFiles"),
    };
  });
  const sites = producer.sites.map((entry: unknown, index: number): ProducerSite => {
    const site = objectOf(entry, `producer.sites[${index}]`);
    exactKeys(site, ["label", "repo", "sha", "path", "line", "blob", "fragment"], `producer.sites[${index}]`);
    return {
      label: text(site.label, "label"),
      repo: text(site.repo, "repo"),
      sha: text(site.sha, "sha"),
      path: text(site.path, "path"),
      line: count(site.line, "line"),
      blob: text(site.blob, "blob"),
      fragment: text(site.fragment, "fragment"),
    };
  });
  return {
    bead: text(raw.bead, "bead"),
    quote: text(raw.quote, "quote"),
    citation: text(raw.citation, "citation"),
    constants: json(raw.constants),
    producer: {
      installedRf: {
        command: text(rf.command, "producer.installedRf.command"),
        version: text(rf.version, "producer.installedRf.version"),
        commit: text(rf.commit, "producer.installedRf.commit"),
        leaves: strings(rf.leaves, "producer.installedRf.leaves"),
        unserved: strings(rf.unserved, "producer.installedRf.unserved"),
      },
      rfSource,
      sites,
    },
    rows,
    tests: strings(raw.tests, "tests"),
  };
}

