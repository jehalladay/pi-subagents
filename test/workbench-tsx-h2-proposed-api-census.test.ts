/** A line that ends a segment before it: a blank line, a list item, a heading, a quote, a table row or a fence. */
const BLOCK_START = /^\s{0,3}(?:[-*+]\s|\d{1,9}[.)]\s|#{1,6}(?:\s|$)|>|\||```|~~~)/;
/** The raw offsets of the line breaks that end a segment. */
function hardBreaks(raw: string): Set<number> {
  const breaks = new Set<number>();
  const lines = raw.split("\n");
  let offset = 0;
  for (let index = 0; index < lines.length - 1; index++) {
    const line = lines[index] ?? "";
    const next = lines[index + 1] ?? "";
    offset += line.length;
    if (line.trim() === "" || next.trim() === "" || BLOCK_START.test(next)) breaks.add(offset);
    offset += 1;
  }
  return breaks;
}
const JOINER = new RegExp(`[\\s_*~^+=\\-${cp(0x2010, 0x2012, 0x2043)}]`, "u");
const LETTER_OR_DIGIT = /[\p{L}\p{N}]/u;

interface Segment {
  readonly letters: string;
  readonly at: readonly number[];
}
/** The SEGMENTs of a raw text: its letters and digits between boundaries, each letter with its raw offset. */
function segmentsOf(raw: string): Segment[] {
  const reading = readingOf(raw);
  const breaks = hardBreaks(raw);
  const segments: Segment[] = [];
  let letters = "";
  let at: number[] = [];
  const flush = (): void => {
    if (letters.length > 0) segments.push({ letters, at });
    letters = "";
    at = [];
  };
  reading.chars.forEach((char, index) => {
    const offset = reading.at[index] ?? 0;
    if (/[a-z0-9]/.test(char)) {
      letters += char;
      at.push(offset);
    } else if (char === "\n") {
      if (breaks.has(offset)) flush();
    } else if (JOINER.test(char)) {
      // A joiner parts no name.
    } else if (LETTER_OR_DIGIT.test(char)) {
      letters += "?";
      at.push(offset);
    } else flush();
  });
  flush();
  return segments;
}

function lineStarts(raw: string): number[] {
  const starts = [0];
  for (let index = 0; index < raw.length; index++) if (raw[index] === "\n") starts.push(index + 1);
  return starts;
}
/** The 0-based line holding `offset`. */
function lineAt(starts: readonly number[], offset: number): number {
  let low = 0;
  let high = starts.length - 1;
  while (low < high) {
    const middle = Math.ceil((low + high) / 2);
    if ((starts[middle] ?? 0) <= offset) low = middle;
    else high = middle - 1;
  }
  return low;
}
/** The raw lines spanning [from, to]. */
function linesSpanning(raw: string, starts: readonly number[], from: number, to: number): string {
  const first = lineAt(starts, from);
  const last = lineAt(starts, to);
  const next = starts[last + 1];
  return raw.slice(starts[first] ?? 0, next === undefined ? raw.length : next - 1);
}

interface Mention {
  readonly family: string;
  readonly line: number;
  readonly marked: boolean;
}
/** Every NAME_FAMILIES match of a raw text, with whether a line it spans carries a marker, in line and family order. */
function mentionsOf(raw: string): Mention[] {
  const starts = lineStarts(raw);
  const found: Mention[] = [];
  for (const segment of segmentsOf(raw)) {
    for (const family of NAME_FAMILIES) {
      for (const match of segment.letters.matchAll(familyPattern(family))) {
        const index = match.index ?? 0;
        const from = segment.at[index] ?? 0;
        const to = segment.at[index + match[0].length - 1] ?? from;
        found.push({ family: family.id, line: lineAt(starts, from) + 1, marked: MARKER.test(plainOf(linesSpanning(raw, starts, from, to))) });
      }
    }
  }
  return found.sort((left, right) => left.line - right.line || (left.family < right.family ? -1 : left.family > right.family ? 1 : 0));
}
const mentionOutcome = (raw: string): string[] => mentionsOf(raw).map(mention => `${mention.family}:${mention.marked ? "marked" : "available"}`);

interface Window {
  readonly plain: string;
  readonly line: number;
}
/** The CLAIM WINDOWs of a raw text: its sentences, broken by "|", a sentence end and the line breaks a segment breaks at. */
function windowsOf(raw: string): Window[] {
  const reading = readingOf(raw);
  const breaks = hardBreaks(raw);
  const starts = lineStarts(raw);
  const windows: Window[] = [];
  let plain = "";
  let first = -1;
  const flush = (): void => {
    if (plain.trim() !== "") windows.push({ plain, line: lineAt(starts, first) + 1 });
    plain = "";
    first = -1;
  };
  reading.chars.forEach((char, index) => {
    const offset = reading.at[index] ?? 0;
    const next = reading.chars[index + 1];
    if (char === "|" || (char === "\n" && breaks.has(offset))) {
      flush();
      return;
    }
    if (first < 0 && char.trim() !== "") first = offset;
    plain += char;
    if ((char === "." || char === "!" || char === "?") && (next === undefined || next.trim() === "")) flush();
  });
  flush();
  return windows;
}
/** Whether a claim window states a Reactive SDK beside a link word, and whether a marker admits it. */
function claimOf(window: Window): "claim" | "marked" | undefined {
  const words = wordsIn(window.plain);
  if (!namesSdk(words) || !linksIn(words, LINK_FAMILY)) return undefined;
  return MARKER.test(window.plain) ? "marked" : "claim";
}
const claimOutcome = (raw: string): string[] => windowsOf(raw).flatMap(window => claimOf(window) ?? []);

interface DocReading {
  readonly walk: Walk;
  readonly docs: string[];
  readonly findings: string[];
  readonly admitted: string[];
  readonly segments: number;
  readonly anchorsRead: string[];
}
/** Acceptance (a) over a tree: every doc file and then the plants (wb-4n55 F1), judged by one loop - their mentions, the unmarked
 * ones as findings; the segments count the walked docs only. */
function readDocs(root: string, plants: readonly Plant[] = []): DocReading {
  const walk = walkTree(root);
  const docs = walk.files.filter(isDoc);
  const findings: string[] = [];
  const admitted: string[] = [];
  const anchorsRead: string[] = [];
  let segments = 0;
  const judged = [...docs.map(path => ({ path, raw: readText(root, path), planted: false })), ...plants.map(plant => ({ path: plant.path, raw: plant.text, planted: true }))];
  for (const { path, raw, planted } of judged) {
    if (raw === undefined) {
      findings.push(`${path}: unreadable`);
      continue;
    }
    if (!planted) segments += segmentsOf(raw).length;
    const anchor = DOC_ANCHORS.find(([file]) => file === path);
    if (anchor !== undefined && plainOf(raw).includes(anchor[1])) anchorsRead.push(path);
    for (const mention of mentionsOf(raw)) {
      const entry = `${path}:${mention.line} ${mention.family}`;
      if (mention.marked) admitted.push(entry);
      else findings.push(`${entry}: named-as-available`);
    }
  }
  return { walk, docs, findings, admitted, segments, anchorsRead };
}
/** Acceptance (b) over a tree's docs/workbench and then the plants (wb-4n55 F1), judged by one loop: every claim window naming a
 * Reactive SDK beside a link word; the window counts are the walked files' only. */
function readClaims(root: string, plants: readonly Plant[] = []): { files: number; windows: number; sdkWindows: number; findings: string[]; admitted: string[] } {
  const files = walkTree(join(root, "docs", "workbench")).files.filter(isDoc);
  const findings: string[] = [];
  const admitted: string[] = [];
  let windows = 0;
  let sdkWindows = 0;
  const judged = [
    ...files.map(path => ({ path: `docs/workbench/${path}`, raw: readText(join(root, "docs", "workbench"), path) ?? "", planted: false })),
    ...plants.map(plant => ({ path: plant.path, raw: plant.text, planted: true })),
  ];
  for (const { path, raw, planted } of judged) {
    for (const window of windowsOf(raw)) {
      if (!planted) {
        windows += 1;
        if (namesSdk(wordsIn(window.plain))) sdkWindows += 1;
      }
      const claim = claimOf(window);
      if (claim === "claim") findings.push(`${path}:${window.line}: claim-unmarked`);
      else if (claim === "marked") admitted.push(`${path}:${window.line}`);
    }
  }
  return { files: files.length, windows, sdkWindows, findings, admitted };
}

/** Plants `files` in a fresh scratch root (a null content is a symlink to the root's first file) and reads it with `read`. */
function withPlantedTree<T>(files: Readonly<Record<string, string | null>>, read: (root: string) => T): T {
  const root = makeScratch("tsx-h2-proposed-api-tree-");
  try {
    for (const [path, content] of Object.entries(files)) {
      const target = join(root, path);
      mkdirSync(dirname(target), { recursive: true });
      if (content === null) symlinkSync(join(root, Object.keys(files)[0] ?? ""), target);
      else writeFileSync(target, content);
    }
    return read(root);
  } finally {
    removeScratch(root);
  }
}

const scriptKindOf = (path: string): ts.ScriptKind =>
  path.endsWith(".tsx") ? ts.ScriptKind.TSX
  : path.endsWith(".jsx") ? ts.ScriptKind.JSX
  : /\.[mc]?js$/.test(path) ? ts.ScriptKind.JS
  : ts.ScriptKind.TS;
/** The literal text of a string literal, a literal + concatenation or a template of literals; undefined otherwise. */
function fold(node: ts.Node): string | undefined {
  if (ts.isStringLiteralLike(node)) return node.text;
  if (ts.isParenthesizedExpression(node)) return fold(node.expression);
  if (ts.isBinaryExpression(node) && node.operatorToken.kind === ts.SyntaxKind.PlusToken) {
    const left = fold(node.left);
    const right = fold(node.right);
    return left === undefined || right === undefined ? undefined : left + right;
  }
  if (ts.isTemplateExpression(node)) {
    let folded = node.head.text;
    for (const span of node.templateSpans) {
      const value = fold(span.expression);
      if (value === undefined) return undefined;
      folded += value + span.literal.text;
    }
    return folded;
  }
  return undefined;
}
const sourceOf = (path: string, source: string): ts.SourceFile => ts.createSourceFile(path, source, ts.ScriptTarget.Latest, true, scriptKindOf(path));
/** The innermost named function a node sits in: a function or method declaration, or a function bound to a variable. */
function enclosingName(node: ts.Node): string {
  for (let current: ts.Node | undefined = node.parent; current !== undefined; current = current.parent) {
    if ((ts.isFunctionDeclaration(current) || ts.isMethodDeclaration(current)) && current.name !== undefined) return current.name.getText();
    if ((ts.isArrowFunction(current) || ts.isFunctionExpression(current)) && ts.isVariableDeclaration(current.parent) && ts.isIdentifier(current.parent.name)) return current.parent.name.text;
  }
  return "<module>";
}
const calleeName = (callee: ts.Expression): string | undefined =>
  ts.isIdentifier(callee) ? callee.text : ts.isPropertyAccessExpression(callee) ? callee.name.text : undefined;

interface ModuleReading {
  readonly names: string[];
  readonly rfSpawns: string[];
  readonly servedReads: string[];
}
/** One module: its name spellings (A3), its rf spawn sites (C1) and its leaves or served reads (C4). */
function readModule(path: string, source: string): ModuleReading {
  const file = sourceOf(path, source);
  const names: string[] = [];
  const rfSpawns: string[] = [];
  const servedReads: string[] = [];
  const judge = (value: string, kind: string): void => {
    const families = [...new Set(mentionsOf(value).map(mention => mention.family))];
    if (families.length > 0) names.push(`${path}: ${kind} ${families.join("+")}`);
  };
  const visit = (node: ts.Node): void => {
    if (ts.isIdentifier(node) || ts.isPrivateIdentifier(node)) judge(node.text, "identifier");
    else if (ts.isStringLiteralLike(node)) judge(node.text, "literal");
    else if (ts.isTemplateExpression(node)) judge([node.head.text, ...node.templateSpans.map(span => span.literal.text)].join(" "), "template");
    else if (ts.isJsxText(node)) judge(node.text, "jsx");
    else if (ts.isRegularExpressionLiteral(node)) judge(node.text, "regex");
    if (ts.isCallExpression(node) || ts.isNewExpression(node)) {
      const name = calleeName(node.expression);
      const first = node.arguments?.[0];
      const command = first === undefined ? undefined : fold(first);
      const binary = command?.trim().split(/\s+/)[0]?.split("/").pop();
      if (name !== undefined && SPAWNERS.includes(name) && (binary === "rf" || binary === "rf.exe")) rfSpawns.push(`${path}#${enclosingName(node)}`);
    }
    if (ts.isPropertyAccessExpression(node) && SERVED_WORDS.includes(node.name.text)) servedReads.push(`${path}: .${node.name.text}`);
    if (ts.isElementAccessExpression(node) && ts.isStringLiteralLike(node.argumentExpression) && SERVED_WORDS.includes(node.argumentExpression.text)) servedReads.push(`${path}: [${node.argumentExpression.text}]`);
    if (ts.isBindingElement(node)) {
      const bound = node.propertyName ?? node.name;
      if (ts.isIdentifier(bound) && SERVED_WORDS.includes(bound.text)) servedReads.push(`${path}: {${bound.text}}`);
    }
    if (ts.isStringLiteralLike(node) && SERVED_WORDS.includes(node.text) && !ts.isElementAccessExpression(node.parent)) servedReads.push(`${path}: "${node.text}"`);
    ts.forEachChild(node, visit);
  };
  visit(file);
  return { names, rfSpawns, servedReads };
}
/** One JSON file's keys and string values that spell a name (an unparsable file is read as text). */
function readJsonNames(path: string, source: string): string[] {
  let parsed: unknown;
  try {
    parsed = JSON.parse(source);
  } catch {
    return mentionsOf(source).length > 0 ? [`${path}: text`] : [];
  }
  const values: string[] = [];
  const collect = (value: unknown): void => {
    if (typeof value === "string") values.push(value);
    else if (Array.isArray(value)) for (const item of value) collect(item);
    else if (isObject(value))
      for (const [key, item] of Object.entries(value)) {
        values.push(key);
        collect(item);
      }
  };
  collect(parsed);
  return values.some(value => mentionsOf(value).length > 0) ? [`${path}: json`] : [];
}

