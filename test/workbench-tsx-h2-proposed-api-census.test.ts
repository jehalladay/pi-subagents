interface Reading {
  readonly chars: readonly string[];
  readonly at: readonly number[];
}
/** The FOLD of a raw text: every character it yields keeps the raw offset it came from. */
function readingOf(raw: string): Reading {
  const chars: string[] = [];
  const at: number[] = [];
  const push = (value: string, offset: number): void => {
    for (const decomposed of value.normalize("NFKD")) {
      if (DROPPED.test(decomposed)) continue;
      const mapped = LOOKALIKES.get(decomposed.codePointAt(0) ?? 0) ?? decomposed;
      for (const lower of mapped.toLowerCase()) {
        chars.push(lower);
        at.push(offset);
      }
    }
  };
  for (const match of raw.matchAll(TOKEN)) {
    const offset = match.index ?? 0;
    if (match[1] !== undefined || match[2] !== undefined) continue;
    const decimal = match[3];
    const hex = match[4] ?? match[6] ?? match[7] ?? match[8] ?? match[9];
    const named = match[5];
    const decoded =
      decimal !== undefined ? pointOf(Number.parseInt(decimal, 10))
      : hex !== undefined ? pointOf(Number.parseInt(hex, 16))
      : named !== undefined ? NAMED_REFERENCES[named]
      : match[10];
    push(decoded ?? match[0], offset);
  }
  return { chars, at };
}
