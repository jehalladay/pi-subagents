const REGEX_PREFIX = "(,=:[!&|?{};";

function skipQuoted(s: string, at: number): number {
	const quote = s[at];
	let i = at + 1;
	while (i < s.length) {
		if (s[i] === "\\") i += 2;
		else if (s[i] === quote) return i + 1;
		else i += 1;
	}
	return s.length;
}

/** Scans from `start` to the unmatched closer at depth 0; records top-level commas in `commas`. */
function skipCode(s: string, start: number, commas?: number[]): number | undefined {
	let depth = 0;
	let prev = "";
	let i = start;
	while (i < s.length) {
		const c = s[i] ?? "";
		const next = s[i + 1] ?? "";
		if (c === "/" && next === "/") {
			const eol = s.indexOf("\n", i);
			i = eol < 0 ? s.length : eol;
			continue;
		}
		if (c === "/" && next === "*") {
			const end = s.indexOf("*/", i + 2);
			i = end < 0 ? s.length : end + 2;
			continue;
		}
		if (c === "'" || c === '"') {
			i = skipQuoted(s, i);
			prev = c;
			continue;
		}
		if (c === "`") {
			i += 1;
			while (i < s.length) {
				if (s[i] === "\\") i += 2;
				else if (s[i] === "`") {
					i += 1;
					break;
				} else if (s[i] === "$" && s[i + 1] === "{") {
					const close = skipCode(s, i + 2);
					if (close === undefined) return undefined;
					i = close + 1;
				} else i += 1;
			}
			prev = "`";
			continue;
		}
		if (c === "/" && (prev === "" || REGEX_PREFIX.includes(prev))) {
			i += 1;
			let inClass = false;
			while (i < s.length) {
				if (s[i] === "\\") i += 2;
				else if (s[i] === "[") {
					inClass = true;
					i += 1;
				} else if (s[i] === "]") {
					inClass = false;
					i += 1;
				} else if (s[i] === "/" && !inClass) {
					i += 1;
					break;
				} else i += 1;
			}
			prev = "/";
			continue;
		}
		if (c === "(" || c === "[" || c === "{") depth += 1;
		else if (c === ")" || c === "]" || c === "}") {
			if (depth === 0) return i;
			depth -= 1;
		} else if (c === "," && depth === 0 && commas) commas.push(i);
		if (!/\s/u.test(c)) prev = c;
		i += 1;
	}
	return undefined;
}

/** Top-level argument texts of the call whose "(" is at `open`; undefined when unbalanced. */
function callArguments(source: string, open: number): readonly string[] | undefined {
	const commas: number[] = [];
	const end = skipCode(source, open + 1, commas);
	if (end === undefined) return undefined;
	const bounds = [open, ...commas, end];
	const args: string[] = [];
	for (let k = 0; k + 1 < bounds.length; k += 1) args.push(source.slice((bounds[k] ?? 0) + 1, bounds[k + 1]));
	return args;
}

const OPTION_MODIFIER = /\b(skip|todo|fails|only)\b\s*(?::\s*(?!false\b)|[,}])/u;
const RUNTIME_SKIP = /\bskip\s*\(|\[\s*["']skip["']\s*\]/u;
const HEAD_MODIFIER = /(?<![.\w$])(?:it|test)((?:\s*\.\s*[A-Za-z]+)*)$/u;
const ALLOWED_HEAD_MODIFIERS = new Set(["concurrent", "sequential"]);
const SHADOWED_BINDING = /\b(?:const|let|var|function|class)\s+(?:it|test|describe|suite)\b|(?<![.\w$])(?:it|test|describe|suite)\s*=(?!=)/u;
const EXPECT_CALL = /\bexpect\s*[.(]|\bassert\s*[.(]/u;
const FOCUS_DOT_CALL = /\b(?:it|test|describe|suite)\s*(?:\.\s*[A-Za-z]+\s*)*\.\s*only\b/u;
const FOCUS_BRACKET_CALL = /\b(?:it|test|describe|suite)\s*\[\s*["']only["']\s*\]/u;

/**
 * Blanks every comment (same length, so offsets survive; the replace regexes carry no u flag, because a u-flag match would
 * collapse an astral character's surrogate pair into one space and shift every later offset) so a commented-out call is never located.
 */
function maskComments(s: string): string {
	let out = "";
	let i = 0;
	while (i < s.length) {
		const c = s[i] ?? "";
		const next = s[i + 1] ?? "";
		if (c === "/" && next === "/") {
			const eol = s.indexOf("\n", i);
			const end = eol < 0 ? s.length : eol;
			out += " ".repeat(end - i);
			i = end;
		} else if (c === "/" && next === "*") {
			const close = s.indexOf("*/", i + 2);
			const end = close < 0 ? s.length : close + 2;
			out += s.slice(i, end).replace(/[^\n]/g, " ");
			i = end;
		} else if (c === "'" || c === '"' || c === "`") {
			let j = i + 1;
			while (j < s.length && s[j] !== c) j += s[j] === "\\" ? 2 : 1;
			out += s.slice(i, j + 1);
			i = j + 1;
		} else {
			out += c;
			i += 1;
		}
	}
	return out;
}

/** Blanks every comment AND every string/template body (same length) so text spelled in a string never counts. */
function maskCode(s: string): string {
	let out = "";
	let i = 0;
	while (i < s.length) {
		const c = s[i] ?? "";
		const next = s[i + 1] ?? "";
		if (c === "/" && next === "/") {
			const eol = s.indexOf("\n", i);
			const end = eol < 0 ? s.length : eol;
			out += " ".repeat(end - i);
			i = end;
		} else if (c === "/" && next === "*") {
			const close = s.indexOf("*/", i + 2);
			const end = close < 0 ? s.length : close + 2;
			out += s.slice(i, end).replace(/[^\n]/g, " ");
			i = end;
		} else if (c === "'" || c === '"' || c === "`") {
			let j = i + 1;
			while (j < s.length && s[j] !== c) j += s[j] === "\\" ? 2 : 1;
			out += c + s.slice(i + 1, j).replace(/[^\n]/g, " ") + (j < s.length ? c : "");
			i = j + 1;
		} else {
			out += c;
			i += 1;
		}
	}
	return out;
}

/** A focused call anywhere in a pinned file narrows the whole run: a census-level red, independent of allowOnly. */
function auditFocus(source: string): string | undefined {
	return FOCUS_DOT_CALL.test(maskCode(source)) || FOCUS_BRACKET_CALL.test(maskComments(source))
		? "[only-focus] the file carries a focused .only call, which silently narrows every sibling case"
		: undefined;
}

function escapeRegExp(text: string): string {
	return text.replace(/[.*+?^${}()|[\]\\]/gu, "\\$&");
}

/** The reporter-name matcher for an it.each title: each format specifier matches any substituted text. */
function eachMatcher(title: string): RegExp {
	const body = title
		.split(/%[sjdoif]/u)
		.map(escapeRegExp)
		.join(".+?");
	return new RegExp(`^(?:.* > )?${body}$`, "u");
}

/** Every way a title can be spelled as a string literal in source: raw and escaped, in each quote style. */
function titleLiterals(title: string): string[] {
	const out: string[] = [];
	for (const quote of ["'", '"', "`"]) {
		out.push(`${quote}${title}${quote}`);
		out.push(`${quote}${title.replace(/\\/gu, "\\\\").split(quote).join(`\\${quote}`)}${quote}`);
	}
	return [...new Set(out)];
}

/**
 * Indices of the "(" of every real call whose first argument is the title literal. A literal that sits inside another
 * string or a comment (a decoy) is never located: the string-blanked mask must still show the opening quote there.
 */
function locateCalls(commentFree: string, codeOnly: string, title: string): number[] {
	const opens = new Set<number>();
	for (const literal of titleLiterals(title)) {
		let from = 0;
		for (;;) {
			const at = commentFree.indexOf(literal, from);
			if (at < 0) break;
			from = at + literal.length;
			if (codeOnly[at] !== literal[0]) continue;
			const before = commentFree.slice(0, at).trimEnd();
			if (before.endsWith("(")) opens.add(before.length - 1);
		}
	}
	return [...opens];
}

/** For `it.each(table)(title, fn)`: the index just before ".each(", located by balanced-scanning the table call. */
function eachHeadEnd(code: string, open: number): number | undefined {
	const between = code.slice(0, open).trimEnd();
	if (!between.endsWith(")")) return undefined;
	const close = between.length - 1;
	let from = between.lastIndexOf(".each(", close);
	while (from >= 0) {
		const reached = skipCode(code, from + ".each(".length);
		if (reached === close) return from;
		from = from > 0 ? between.lastIndexOf(".each(", from - 1) : -1;
	}
	return undefined;
}

type AssertionMode = "probe" | "lexical";

interface Evidence {
	/** Collect-only listing entries for the pin's tier (default gate config, or the rf config for a native-read pin). */
	readonly listing: readonly ListedCase[];
	/** Assertion-reach records from the probe run (probe mode only). */
	readonly probe: readonly ProbeRecord[];
	readonly mode: AssertionMode;
}

/**
 * Returns the problems for one pinned title, each beginning with a [category] naming its true cause. Empty only when the
 * reporter lists the title exactly once (an it.each pin: its declared instance count), the located call is a plain
 * undisabled it()/test(), and the case reached at least one assertion. `file` is the real path the reporter prints.
 */
function auditPin(evidence: Evidence, file: string, source: string, pin: Pick<Pin, "title" | "each">): string[] {
	const problems: string[] = [];
	const title = pin.title;
	const isEach = pin.each !== undefined;
	const matcher = eachMatcher(title);
	const matches = (name: string): boolean => (isEach ? matcher.test(name) : name === title || name.endsWith(` > ${title}`));
	const listed = evidence.listing.filter((entry) => entry.file === file && matches(entry.name));

	const commentFree = maskComments(source);
	const codeOnly = maskCode(source);
	if (SHADOWED_BINDING.test(codeOnly)) problems.push("[shadowed-binding] the file rebinds it/test/describe/suite, so a registered-looking call may not be the runner's");

	let callBody: string | undefined;
	const opens = locateCalls(commentFree, codeOnly, title);
	if (opens.length === 0) {
		problems.push("[title-absent] no it()/test() call carries the title: it is absent from the code, or appears only inside a comment or a string");
	} else if (opens.length > 1) {
		problems.push(`[source-unlocated] the title is a call argument ${opens.length} times in the source, expected exactly once`);
	} else {
		const open = opens[0] ?? 0;
		let head = codeOnly.slice(0, open).trimEnd();
		let headProblem: string | undefined;
		if (isEach) {
			const eachAt = eachHeadEnd(codeOnly, open);
			if (eachAt === undefined) headProblem = "[call-head] the pinned it.each table call could not be located";
			else head = codeOnly.slice(0, eachAt).trimEnd();
		} else if (/[)\]]$/u.test(head)) {
			headProblem = "[head-modifier] the call head is a modifier expression (skipIf/runIf/bracket form), not a plain it()/test()";
		}
		if (!headProblem) {
			const headMatch = HEAD_MODIFIER.exec(head);
			if (!headMatch) {
				headProblem = "[call-head] the call head is not a plain it()/test() (member call, aliased or shadowed binding)";
			} else {
				const modifiers = (headMatch[1] ?? "")
					.split(".")
					.map((part) => part.trim())
					.filter((part) => part.length > 0);
				const blocked = modifiers.filter((part) => !ALLOWED_HEAD_MODIFIERS.has(part));
				if (blocked.length > 0) headProblem = `[head-modifier] the call head carries .${blocked.join(".")}`;
			}
		}
		if (headProblem) problems.push(headProblem);
		const args = callArguments(codeOnly, open);
		if (!args) {
			problems.push("[source-unbalanced] the pinned call could not be scanned to its closing parenthesis");
		} else {
			callBody = args.slice(1).join(",");
			for (const arg of args.slice(1)) {
				const text = arg.trim();
				if (text.startsWith("{")) {
					const option = OPTION_MODIFIER.exec(text);
					if (option) problems.push(`[options-modifier] the options argument sets ${option[1]}`);
				} else if (RUNTIME_SKIP.test(text)) {
					problems.push("[runtime-skip] the case body calls skip() (a runtime skip the collect-only run cannot see)");
				}
			}
		}
	}

	if (listed.length === 0) {
		if (opens.length === 1 && problems.every((line) => line.startsWith("[runtime-skip]") || line.startsWith("[shadowed-binding]"))) {
			problems.push(
				"[not-collected] the title is present as a plain call but the runner does not collect it: an enclosing describe/suite modifier or option (skip, todo, skipIf, runIf), a conditional or never-called registration, or an emptied each table",
			);
		}
		return problems;
	}
	if (isEach) {
		if (listed.length !== pin.each) problems.push(`[each-count] the collect-only listing has ${listed.length} instances, expected exactly ${pin.each}`);
	} else if (listed.length > 1) problems.push(`[duplicate] the collect-only listing has ${listed.length} such cases, expected exactly one`);

	if (evidence.mode === "lexical") {
		if (callBody !== undefined && !EXPECT_CALL.test(callBody)) problems.push("[no-assertion-text] the located case body spells no expect()/assert call (lexical check only: this case is never run here)");
		return problems;
	}
	const reached = evidence.probe.filter((record) => record.file === file && matches(record.test));
	if (reached.length === 0) problems.push("[probe-missing] the probe run recorded no result for this case (it did not run in the probe)");
	else if (reached.length !== listed.length) problems.push(`[probe-missing] the probe recorded ${reached.length} runs for ${listed.length} listed cases`);
	else if (reached.some((record) => record.calls < 1)) problems.push("[no-assertion-reached] the case ran but reached no assertion (empty body, guarded early return, dead branch, helper never called or runtime skip)");
	return problems;
}

