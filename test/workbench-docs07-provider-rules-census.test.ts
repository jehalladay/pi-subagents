function listTsFiles(root: string): string[] {
	const out: string[] = [];
	for (const dir of ["test", "src"]) {
		const base = resolve(root, dir);
		if (!existsSync(base)) continue;
		for (const entry of readdirSync(base, { recursive: true, encoding: "utf8" })) {
			if (entry.endsWith(".ts")) out.push(`${dir}/${entry}`);
		}
	}
	return out.sort();
}

/** The files (other than `except`) whose text matches the pattern. */
function absenceHits(files: ReadonlyMap<string, string>, pattern: RegExp, except: string): string[] {
	return [...files.entries()].filter(([path, text]) => path !== except && pattern.test(text)).map(([path]) => path);
}

