interface VitestGlobs {
	readonly include: readonly string[];
	readonly exclude: readonly string[];
}

interface TierEnv {
	readonly gate: VitestGlobs;
	readonly rf: VitestGlobs;
	readonly forgeToml: string;
	readonly packageJson: string;
}

function globToRegExp(glob: string): RegExp {
	let out = "";
	for (let i = 0; i < glob.length; i += 1) {
		const c = glob[i] ?? "";
		if (c === "*" && glob[i + 1] === "*") {
			if (glob[i + 2] === "/") {
				out += "(?:.*/)?";
				i += 2;
			} else {
				out += ".*";
				i += 1;
			}
		} else if (c === "*") out += "[^/]*";
		else if (c === "?") out += "[^/]";
		else out += c.replace(/[.+^${}()|[\]\\]/gu, "\\$&");
	}
	return new RegExp(`^${out}$`, "u");
}

function matchesAny(patterns: readonly string[], file: string): boolean {
	return patterns.some((pattern) => globToRegExp(pattern).test(file));
}

function globsOf(config: unknown): VitestGlobs {
	const test = (config as { test?: { include?: unknown; exclude?: unknown } }).test ?? {};
	const strings = (value: unknown): readonly string[] => (Array.isArray(value) ? value.filter((item): item is string => typeof item === "string") : []);
	return { include: strings(test.include), exclude: strings(test.exclude) };
}

/** The text of one forge.toml table body: after its exact header line, up to the next table header. */
function tomlTable(toml: string, header: string): string | undefined {
	const lines = toml.split("\n");
	const at = lines.indexOf(`[${header}]`);
	if (at < 0) return undefined;
	const rest = lines.slice(at + 1);
	const next = rest.findIndex((line) => /^\s*\[/u.test(line));
	return (next < 0 ? rest : rest.slice(0, next)).join("\n");
}

function quotedValue(body: string, key: string): string | undefined {
	return new RegExp(`^${escapeRegExp(key)}\\s*=\\s*"([^"]*)"\\s*$`, "mu").exec(body)?.[1];
}

/** The command line forge runs for a named command: a [build.commands.<name>] table or a [build.commands] one-liner. */
function forgeCommand(toml: string, name: string): string | undefined {
	const table = tomlTable(toml, `build.commands.${name}`);
	if (table !== undefined) return quotedValue(table, "command");
	return quotedValue(tomlTable(toml, "build.commands") ?? "", name);
}

function forgeGate(toml: string): readonly string[] {
	const list = /^gate\s*=\s*\[([^\]]*)\]/mu.exec(tomlTable(toml, "build") ?? "")?.[1] ?? "";
	return [...list.matchAll(/"([^"]+)"/gu)].map((m) => m[1] ?? "");
}

function packageTestScript(packageJson: string): string | undefined {
	try {
		const parsed: unknown = JSON.parse(packageJson);
		const scripts = (parsed as { scripts?: Record<string, unknown> }).scripts;
		const value = scripts?.test;
		return typeof value === "string" ? value : undefined;
	} catch {
		return undefined;
	}
}

/** A tier label is a claim about the gate: verify it against the config modules and forge registration, never prose. */
function auditTier(pin: Pin, env: TierEnv): string | undefined {
	if (pin.tier === "default-gate") {
		if (!matchesAny(env.gate.include, pin.file)) return `[tier-truth] ${pin.file} is labelled default-gate but is not matched by the vitest include`;
		if (matchesAny(env.gate.exclude, pin.file)) return `[tier-truth] ${pin.file} is labelled default-gate but is excluded from the vitest run`;
		if (!forgeGate(env.forgeToml).includes("test")) return `[tier-truth] ${pin.file} is labelled default-gate but forge.toml [build].gate does not run the test step`;
		const command = forgeCommand(env.forgeToml, "test");
		if (command !== "npm run test") return `[tier-truth] ${pin.file} is labelled default-gate but the forge.toml test command is ${JSON.stringify(command)}, not plain "npm run test"`;
		const script = packageTestScript(env.packageJson);
		if (script !== "vitest run") return `[tier-truth] ${pin.file} is labelled default-gate but the package.json test script is ${JSON.stringify(script)}, not plain "vitest run"`;
		return undefined;
	}
	if (!pin.command || !pin.config) return `[tier-truth] ${pin.file} is labelled native-read but names no forge.toml command and config`;
	if (!matchesAny(env.gate.exclude, pin.file)) return `[tier-truth] ${pin.file} is labelled native-read but the default vitest run does not exclude it`;
	if (!matchesAny(env.rf.include, pin.file)) return `[tier-truth] ${pin.file} is labelled native-read but ${pin.config} does not include it`;
	if (matchesAny(env.rf.exclude, pin.file)) return `[tier-truth] ${pin.file} is labelled native-read but ${pin.config} excludes it`;
	const command = forgeCommand(env.forgeToml, pin.command);
	if (command === undefined) return `[tier-truth] ${pin.file} names forge.toml command ${pin.command}, which does not exist`;
	if (!/\bvitest run\b/u.test(command) || !new RegExp(`--config ${escapeRegExp(pin.config)}(?:\\s|$)`, "u").test(command)) {
		return `[tier-truth] forge.toml command ${pin.command} does not run vitest with --config ${pin.config}`;
	}
	return undefined;
}

