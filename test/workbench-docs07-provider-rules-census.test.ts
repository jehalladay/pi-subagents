/**
 * The rendered view of a markdown document: fenced code blocks and HTML comments removed, with neither able to open
 * inside the other. Heading uniqueness and section extraction both read this one view.
 */
function renderedLines(doc: string): string[] {
	const out: string[] = [];
	let fence: string | undefined;
	let inComment = false;
	for (const raw of doc.split("\n")) {
		let line = raw;
		if (fence !== undefined) {
			if (line.trim().startsWith(fence)) fence = undefined;
			continue;
		}
		if (inComment) {
			const close = line.indexOf("-->");
			if (close < 0) continue;
			inComment = false;
			line = line.slice(close + 3);
		} else {
			const opener = /^\s{0,3}(`{3,}|~{3,})/u.exec(line);
			if (opener) {
				fence = (opener[1] ?? "").slice(0, 3);
				continue;
			}
		}
		for (;;) {
			const open = line.indexOf("<!--");
			if (open < 0) break;
			const close = line.indexOf("-->", open + 4);
			if (close < 0) {
				line = line.slice(0, open);
				inComment = true;
				break;
			}
			line = line.slice(0, open) + line.slice(close + 3);
		}
		out.push(line);
	}
	return out;
}

/** Section body lines of the rendered view: after the exact "## heading" line, bounded at the next level-1/2 heading or EOF. */
function sectionBody(rendered: readonly string[], heading: string): { readonly count: number; readonly body: string } {
	const marks = rendered.map((line, index) => (line === `## ${heading}` ? index : -1)).filter((index) => index >= 0);
	if (marks.length !== 1) return { count: marks.length, body: "" };
	const rest = rendered.slice((marks[0] ?? 0) + 1);
	const next = rest.findIndex((line) => /^#{1,2} /u.test(line));
	const lines = next < 0 ? rest : rest.slice(0, next);
	return { count: 1, body: lines.filter((line) => line.trim().length > 0).join("\n") };
}

function auditDocs(doc: string): string[] {
	const problems: string[] = [];
	const rendered = renderedLines(doc);
	for (const heading of SECTION_ORDER) {
		const { count, body } = sectionBody(rendered, heading);
		if (count !== 1) {
			problems.push(`[docs-heading] ${DOC} has ${count} rendered lines exactly "## ${heading}", expected one`);
			continue;
		}
		if (body !== SECTION_BODIES[heading]) problems.push(`[docs-section] ${DOC} section "${heading}" is not the exact frozen body (every sentence, nothing added, nothing removed)`);
	}
	return problems;
}

