/** Violations of one row, each beginning with `<row id>/<half id>`. Empty only when every pin is live, truthful and asserting. */
function rowViolations(row: Row, collected: Collected, locate: (file: string) => PinLocation, env: TierEnv, scan: ReadonlyMap<string, string>, exists: (file: string) => boolean): string[] {
	const out: string[] = [];
	let from = 0;
	const frozen = SECTION_BODIES[row.section];
	if (frozen === undefined) out.push(`${row.id}: section "${row.section}" is not one of the six frozen sections`);
	else if (!frozen.includes(row.quote)) out.push(`${row.id}: the row quote is not inside the frozen "${row.section}" body: ${row.quote}`);
	for (const half of row.halves) {
		const where = `${row.id}/${half.id}`;
		const at = row.quote.indexOf(half.clause, from);
		if (at < 0) out.push(`${where}: clause "${half.clause}" is not inside the row quote in order`);
		else from = at;
		if (half.pins.length === 0) {
			if ((half.reason ?? "").trim().length < 40) out.push(`${where}: unpinned half carries no reason`);
			if (half.absence) {
				for (const hit of absenceHits(scan, half.absence.pattern, SELF)) {
					out.push(`${where}: [absence-broken] ${hit} now mentions ${half.absence.label}, so this unpinned half has a case to flip to a pin`);
				}
			}
			if (half.awaits && exists(half.awaits.file)) {
				out.push(`${where}: [pending-landed] ${half.awaits.file} (${half.awaits.oracleBead}) has landed: flip this half from pending to a pin in the same commit`);
			}
			continue;
		}
		if (half.reason !== undefined) out.push(`${where}: carries both pins and an unpinned reason`);
		for (const pin of half.pins) {
			if (!pin.file.startsWith("test/")) out.push(`${where}: ${pin.file} is not under test/`);
			if (!pin.title.trim()) {
				out.push(`${where}: a pin in ${pin.file} has an empty title`);
				continue;
			}
			const tier = auditTier(pin, env);
			if (tier) out.push(`${where}: ${pin.file} :: ${pin.title}: ${tier}`);
			if (!exists(pin.file)) {
				out.push(`${where}: ${pin.file} :: ${pin.title}: [file-missing] the pinned file does not exist`);
				continue;
			}
			const location = locate(pin.file);
			const focus = auditFocus(location.source);
			if (focus) out.push(`${where}: ${pin.file}: ${focus}`);
			const evidence: Evidence =
				pin.tier === "native-read"
					? { listing: collected.rf.cases, probe: [], mode: "lexical" }
					: { listing: collected.gate.cases, probe: collected.probe.records, mode: "probe" };
			for (const problem of auditPin(evidence, location.absolute, location.source, pin)) out.push(`${where}: ${pin.file} :: ${pin.title}: ${problem}`);
		}
	}
	return out;
}

function coverage(rows: readonly Row[]): { readonly pinned: string[]; readonly unpinned: string[] } {
	const pinned: string[] = [];
	const unpinned: string[] = [];
	for (const row of rows) for (const half of row.halves) (half.pins.length > 0 ? pinned : unpinned).push(`${row.id}/${half.id}`);
	return { pinned, unpinned };
}

