function wordsOf(text: string): string[] {
  const split = text
    .normalize("NFKC")
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1 $2");
  return split.toLowerCase().match(/[a-z0-9]+/g) ?? [];
}
interface SubjectPair {
  readonly words: readonly [string, string];
  readonly subject: string;
}
/** The title's CamelCase names, each cut into its words. */
function titleNamesOf(title: string): string[][] {
  return title
    .split(/[^A-Za-z0-9]+/)
    .filter(token => /[a-z][A-Z]/.test(token))
    .map(wordsOf);
}
/** The subject vocabulary, derived from the bead title: see READINGS. */
function vocabularyOf(title: string): SubjectPair[] {
  const names = titleNamesOf(title);
  const sdks = names.filter(words => words.at(-1) === "sdk");
  const subjects = [...new Set(sdks.flatMap(words => words.filter(word => sdks.some(other => other !== words && !other.includes(word)))))];
  const pairs = new Map<string, SubjectPair>();
  for (const words of names) {
    for (let index = 0; index + 1 < words.length; index += 1) {
      const pair: [string, string] = [words[index], words[index + 1]];
      const subject = subjects.find(word => pair.includes(word));
      if (subject !== undefined) pairs.set(pair.join(" "), { words: pair, subject });
    }
  }
  return [...pairs.values()].sort((left, right) => left.words.join(" ").localeCompare(right.words.join(" ")));
}
function subjectsIn(words: readonly string[], vocabulary: readonly SubjectPair[]): string[] {
  const found = new Set<string>();
  words.forEach((word, index) => {
    for (const pair of vocabulary) {
      if (word === pair.words[0] && words[index + 1] === pair.words[1]) found.add(pair.subject);
      if (word.includes(pair.words.join(""))) found.add(pair.subject);
    }
  });
  return [...found].sort();
}
/**
 * The subjects one text names. Two words are adjacent only inside one segment (READINGS SEGMENTS names what this census
 * claims of it): a space, "_" and "-" are the joining members claimed and "?" and ":" the ending characters claimed, so
 * `config.query ?? sdkQuery` reads no "query sdk" while "the reactive query engine" and "@acme/reactive-query" do; whether
 * "." or "/" joins a segment (deferred to wb-km7q.13), and what else of the class below joins one beyond the words' own
 * ASCII letters, are NOT CLAIMED.
 */
function readSubjects(text: string, vocabulary: readonly SubjectPair[]): string[] {
  const segments = visibleOf(text).split(/[^\p{L}\p{N}\s_./-]+/u);
  return [...new Set(segments.flatMap(segment => subjectsIn(wordsOf(segment), vocabulary)))].sort();
}
/**
 * The visible spelling (READINGS SPELLING names what this census claims of it: the zero-width space, the soft hyphen and the
 * combining grapheme joiner C1's plants spell are removed, so they do not split a name); what else this removes, and its
 * NFKC fold, are NOT CLAIMED.
 */
function visibleOf(text: string): string {
  return text.replace(/[\p{Cf}\p{Default_Ignorable_Code_Point}]/gu, "").normalize("NFKC");
}
function codePointOf(value: number): string {
  return value <= 0x10ffff ? String.fromCodePoint(value) : "";
}
/**
 * A text with its escapes decoded (READINGS SPELLING names the forms this census claims, as C1's plants spell them: \u0071,
 * \x71, \u{51}, \n read as a space, \Q read as Q, &#81;, &#x51; and %20); every other form this decodes is NOT CLAIMED.
 * R-ENCODED names the encodings that are not a JS escape, an HTML numeric character reference or a URL percent escape.
 */
function decodedOf(text: string): string {
  return text
    .replace(/\\(?:u\{([0-9a-fA-F]{1,6})\}|u([0-9a-fA-F]{4})|x([0-9a-fA-F]{2})|([\s\S]))/g, (_whole, brace?: string, four?: string, two?: string, other?: string) => {
      const hex = brace ?? four ?? two;
      if (hex !== undefined) return codePointOf(Number.parseInt(hex, 16));
      return other !== undefined && "bfnrtv0".includes(other) ? " " : (other ?? "");
    })
    .replace(/&#(?:[xX]([0-9a-fA-F]{1,6})|(\d{1,7}));/g, (_whole, hex?: string, decimal?: string) => codePointOf(hex !== undefined ? Number.parseInt(hex, 16) : Number(decimal)))
    .replace(/%([0-9a-fA-F]{2})/g, (_whole, two: string) => String.fromCharCode(Number.parseInt(two, 16)));
}
/** The subjects a text names as written or with its escapes decoded. */
function textSubjects(text: string, vocabulary: readonly SubjectPair[]): string[] {
  const raw = readSubjects(text, vocabulary);
  const decoded = decodedOf(text);
  return decoded === text ? raw : [...new Set([...raw, ...readSubjects(decoded, vocabulary)])].sort();
}
/**
 * A line's leading comment marker (`//`, `/*`, `*`, `#`), dropped where a pair is read across a line break. This census
 * claims the continuations READINGS SEGMENTS names, one plant each, and not the drop of any one marker.
 */
const COMMENT_LEAD = /^\s*(?:\/\/+|\/\*+|\*+|#+)\s?/;
/** `<path>:<line> <subject>` for each line naming a subject, and for a pair split across a line break (read at its first line). */
function findingsOf(path: string, text: string, vocabulary: readonly SubjectPair[]): string[] {
  const lines = text.split(/\r?\n/);
  const subjects = lines.map(line => textSubjects(line, vocabulary));
  const findings: string[] = [];
  lines.forEach((line, index) => {
    const here = subjects[index];
    const next = index + 1 < lines.length ? lines[index + 1] : undefined;
    const split =
      next === undefined
        ? []
        : textSubjects(`${line} ${next.replace(COMMENT_LEAD, "")}`, vocabulary).filter(subject => !here.includes(subject) && !subjects[index + 1].includes(subject));
    for (const subject of [...new Set([...here, ...split])].sort()) findings.push(`${path}:${index + 1} ${subject}`);
  });
  return findings;
}

