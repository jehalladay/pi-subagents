function globToRegExp(glob: string): RegExp {
  let out = "";
  for (let i = 0; i < glob.length; i += 1) {
    const c = glob[i] ?? "";
    if (c === "*" && glob[i + 1] === "*") {
      if (glob[i + 2] === "/") {
        out += "(?:.*/)?";
        i += 2;
      } else {
        out += ".*";
        i += 1;
      }
    } else if (c === "*") out += "[^/]*";
    else out += c.replace(/[.+^${}()|[\]\\?]/gu, "\\$&");
  }
  return new RegExp(`^${out}$`, "u");
}

function matchesAny(patterns: readonly string[], file: string): boolean {
  return patterns.some((pattern) => globToRegExp(pattern).test(file));
}

function gateConfigOf(config: unknown): GateConfig {
  const test = (config as { test?: { include?: unknown; exclude?: unknown } }).test ?? {};
  const strings = (value: unknown): readonly string[] => (Array.isArray(value) ? value.filter((item): item is string => typeof item === "string") : []);
  return { include: strings(test.include), exclude: strings(test.exclude) };
}

/** A tier label is a claim about the gate config: verify it, never carry it from prose. */
function auditTier(pin: Pin, gateConfig: GateConfig, forgeToml: string): string | undefined {
  if (pin.tier === "default-gate") {
    if (!matchesAny(gateConfig.include, pin.file)) return `[tier-truth] ${pin.file} is labelled default-gate but is not matched by the vitest include`;
    if (matchesAny(gateConfig.exclude, pin.file)) return `[tier-truth] ${pin.file} is labelled default-gate but is excluded from the vitest run`;
    return undefined;
  }
  if (!pin.command) return `[tier-truth] ${pin.file} is labelled forge-command but names no forge.toml command`;
  if (!forgeToml.includes(`[build.commands.${pin.command}]`)) return `[tier-truth] ${pin.file} names forge.toml command ${pin.command}, which does not exist`;
  return undefined;
}

