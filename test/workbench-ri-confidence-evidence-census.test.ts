const RECORD_MARKS: readonly string[] = [...new Set([...stringLeaves(EVIDENCE), VC_FIELD, PS_FIELD, PP_FIELD])];
/** THE UNTIL-THEN POSTURE checker of a real carry against the base carry of its seam: the codes it breaks. */
function postureOf(carry: Carry, base: Carry, placement: Placement | null): string[] {
  const codes: string[] = [];
  if (canonical(Object.keys(carry.reading).sort()) !== canonical([...READING_KEYS])) codes.push("reading:shape");
  if (at(carry.reading.source, OUTPUT_TEXT) !== at(carry.handed, OUTPUT_TEXT)) codes.push("fold:output.text");
  if (placement !== null && canonical(at(carry.reading.source, placement.path)) !== canonical(at(carry.handed, placement.path))) codes.push("rewrite:evidence");
  if (JSON.stringify(carry.topology) !== JSON.stringify(base.topology)) codes.push("projection:moved");
  const had = new Set(numericLeaves(base.topology).map(([path, value]) => `${path}=${value}`));
  if (numericLeaves(carry.topology).some(([path, value]) => !had.has(`${path}=${value}`))) codes.push("number:added");
  if (stringLeaves(carry.topology).some(text => RECORD_MARKS.some(mark => text.includes(mark)))) codes.push("surfaced");
  return codes;
}
