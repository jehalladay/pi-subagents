/** THE JUDGE: the codes an echo of `record` breaks, sorted. */
function violationsOf(record: JsonObject, echo: JsonObject): string[] {
  const codes = new Set<string>();
  if (Object.keys(echo).some(key => key !== "carried" && key !== "calibration")) codes.add("echo:extra-key");
  const carried = echo.carried;
  if (!isJsonObject(carried)) codes.add("carried:missing");
  else {
    const given = entriesOf(record);
    const kept = entriesOf(carried);
    if (kept.length > given.length) codes.add("class:added");
    if (kept.length < given.length) codes.add("class:dropped");
    for (let index = 0; index < Math.min(given.length, kept.length); index += 1) {
      const from = given[index];
      const to = kept[index];
      if (from === undefined || to === undefined) continue;
      if (to[CLASS_FIELD] !== from[CLASS_FIELD]) {
        codes.add("class:relabeled");
        if (UPGRADE_LABELS.includes(String(to[CLASS_FIELD])) && !UPGRADE_LABELS.includes(String(from[CLASS_FIELD]))) codes.add("class:upgraded");
      }
      if (canonical(to.values) !== canonical(from.values)) codes.add("values:rewritten");
      if (canonical(without(to, [CLASS_FIELD, "values"])) !== canonical(without(from, [CLASS_FIELD, "values"]))) codes.add("class:rewritten");
    }
    const ranking = objectOf(record.ranking, "record ranking");
    const carriedRanking = carried.ranking;
    if (!isJsonObject(carriedRanking)) codes.add("ranking:dropped");
    else if (canonical(carriedRanking[PS_FIELD]) === canonical(ranking[PP_FIELD]) && canonical(carriedRanking[PP_FIELD]) === canonical(ranking[PS_FIELD])) {
      codes.add("ranking:swapped");
    } else if (canonical(Object.keys(carriedRanking).sort()) !== canonical(Object.keys(ranking).sort())) codes.add("ranking:renamed");
    else if (canonical(carriedRanking) !== canonical(ranking)) codes.add("ranking:rewritten");
    if (canonical(carried.calibration) !== canonical(record.calibration)) codes.add("calibration:rewritten");
    for (const key of new Set([...Object.keys(record), ...Object.keys(carried)])) {
      if (key === "evidence" || key === "ranking" || key === "calibration") continue;
      if (canonical(carried[key]) !== canonical(record[key])) codes.add(key === VC_FIELD ? "verbal:rewritten" : "carried:rewritten");
    }
  }
  const given = new Set(numericLeaves(record).map(([path]) => `carried.${path}`));
  if (numericLeaves(echo).some(([path]) => !given.has(path))) codes.add("number:added");
  const expected = calibrationReading(record.calibration);
  const reading = echo.calibration;
  const surfaced = isJsonObject(reading) && isJsonObject(reading.surfaced) ? reading.surfaced : undefined;
  const parts: JsonObject = isJsonObject(record.calibration) ? record.calibration : {};
  if (!isJsonObject(reading) || Object.keys(reading).length !== 1) codes.add("calibration:untyped");
  else if (isJsonObject(expected.surfaced)) {
    if (surfaced === undefined) codes.add("calibration:suppressed-complete");
    else if (canonical(surfaced) !== canonical(expected.surfaced)) codes.add("calibration:defaulted");
  } else if (surfaced !== undefined) {
    codes.add("calibration:surfaced-incomplete");
    if (CALIBRATION_PARTS.some(part => !presentVerbatim(parts[part]) || surfaced[part] !== parts[part])) codes.add("calibration:defaulted");
  } else if (canonical(reading.suppressed) !== canonical(expected.suppressed)) codes.add("calibration:untyped");
  return [...codes].sort();
}
