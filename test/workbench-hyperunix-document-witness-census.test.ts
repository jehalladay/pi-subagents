/** W5 and W8: a header's R-HIDDEN reading: the text before the source's first comment close, its comment lines joined (a line
 * break, the gutter star and the spaces after it read as one space); the lead counted; after the one lead, the text up to the
 * second semicolon (the second clause's end), split at commas, semicolons and or. */
function headerReading(source: string): HeaderReading {
  const header = source.split("*/")[0].replace(/\n \*\s+/g, " ");
  const parts = header.split(LEAD);
  if (parts.length !== 2) return { leads: parts.length - 1, forms: [] };
  const tail = parts[1];
  const first = tail.indexOf(";");
  const second = first === -1 ? -1 : tail.indexOf(";", first + 1);
  return { leads: 1, forms: second === -1 ? [] : tail.slice(0, second).split(/,\s*(?:or\s+)?|;\s*|\s+or\s+/) };
}
