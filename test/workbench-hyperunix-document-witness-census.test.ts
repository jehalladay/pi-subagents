/** W3 and W7: a holder's own data property of the given enumerability, read census-side, else undefined. */
function ownData(holder: unknown, key: string | symbol | undefined, enumerable: boolean): unknown {
  if (key === undefined || holder === null || (typeof holder !== "object" && typeof holder !== "function")) return undefined;
  const property = Object.getOwnPropertyDescriptor(holder, key);
  return property !== undefined && "value" in property && property.enumerable === enumerable ? property.value : undefined;
}
/** W3 and W7: a holder's own accessor property of the given enumerability, its getter run census-side, else undefined. */
function ownGetter(holder: unknown, key: string | symbol | undefined, enumerable: boolean): unknown {
  if (key === undefined || holder === null || (typeof holder !== "object" && typeof holder !== "function")) return undefined;
  const property = Object.getOwnPropertyDescriptor(holder, key);
  return property?.get !== undefined && property.enumerable === enumerable ? Reflect.apply(property.get, holder, []) : undefined;
}
const symbolsOf = (holder: unknown): symbol[] => (holder !== null && (typeof holder === "object" || typeof holder === "function") ? Object.getOwnPropertySymbols(holder) : []);
const prototypeOf = (value: unknown): unknown => (value !== null && typeof value === "object" ? Object.getPrototypeOf(value) : undefined);
const isEmptyArray = (value: unknown): boolean => Array.isArray(value) && value.length === 0;
/** The function a holder holds at key as an enumerable own data property, called census-side; true when there was one. */
function callOwn(holder: unknown, key: string): boolean {
  const value = ownData(holder, key, true);
  if (typeof value !== "function") return false;
  Reflect.apply(value, holder, []);
  return true;
}
/** The text of a Uint8Array that is not a Buffer, else undefined. */
