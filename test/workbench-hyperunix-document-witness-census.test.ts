/** W6: every recorder recordedPlant makes, so that W6 can tell a replaced binding from an original one. */
const RECORDERS = new WeakSet<object>();
/** W6: hiddenPlant with each function-valued enumerable data binding replaced by a recorder that keeps the function's own
 * enumerable data and pushes the binding's name to calls whenever it is called. */
function recordedPlant(calls: string[]): object {
  const namespace = hiddenPlant();
  for (const key of Object.keys(namespace)) {
    const original: unknown = Object.getOwnPropertyDescriptor(namespace, key)?.value;
    if (typeof original !== "function") continue;
    const recorder = Object.assign((...args: unknown[]): unknown => {
      calls.push(key);
      return Reflect.apply(original, undefined, args);
    }, { ...original });
    RECORDERS.add(recorder);
    Object.defineProperty(namespace, key, { enumerable: true, writable: true, configurable: true, value: recorder });
  }
  return namespace;
}
