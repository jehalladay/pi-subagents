/** W7: a walk's outcome over a namespace: its reading, or the one error it may throw. */
function outcome(namespace: object, walk: Walk): unknown {
  try {
    return walked({ ".": namespace }, walk);
  } catch (error) {
    return error instanceof Error && error.message.includes(" is a Proxy") ? "throws: is a Proxy" : `throws: ${String(error)}`;
  }
}

/** W9 and ROSTER: one element of a list as a source spells it: its id, and the sha256 of its probe's and its present's
 * initializer text exactly as written ('absent' for an id that is not a string literal or a property the element lacks). */
interface CaseRow {
  readonly id: string;
  readonly probe: string;
  readonly present: string;
}
/** W9 and ROSTER: a top-level declaration the cases name, with the sha256 of its statement's text. */
interface SharedDeclaration {
  readonly name: string;
  readonly digest: string;
}
interface CaseReading {
  /** Each list's rows, in source order; none for a list declared other than once. */
  readonly rows: readonly (readonly CaseRow[])[];
  /** The top-level declarations the rows' probes and presents name, directly or through one another, in source order. */
  readonly shared: readonly SharedDeclaration[];
}
const ABSENT = "absent";
const sha256 = (text: string): string => createHash("sha256").update(text).digest("hex");
/** W9: an object literal's property assignment of the given name, else undefined. */
function assignment(element: ts.ObjectLiteralExpression, name: string): ts.Expression | undefined {
  for (const property of element.properties) if (ts.isPropertyAssignment(property) && ts.isIdentifier(property.name) && property.name.text === name) return property.initializer;
  return undefined;
}
/** W9: whether caseReading reads an element: an object literal each of whose properties is a property assignment whose key is
 * an identifier or a reserved word (Q64). W9's pages carry a spread, a computed key and a method as an element's last property
 * (Q15, Q16) and before another property (Q29, Q30, Q17), a numeric-literal key last and first (Q58, Q59), a quoted and a
 * bigint-literal key, a getter and a setter, and a shorthand property (Q60-Q63); ROSTER's reader pin holds the rule for every
 * other position and form (header). */
const plainElement = (element: ts.Expression): element is ts.ObjectLiteralExpression =>
  ts.isObjectLiteralExpression(element) && element.properties.every((property) => ts.isPropertyAssignment(property) && ts.isIdentifier(property.name));
/** W9: the array literal a list's one const declaration spells: its initializer, or the one argument of a call of a plain name
 * that its initializer is, when a top-level function, class or plain-named variable declaration of the source declares that
 * name (the name then pushed to callees, a name the rows name); else undefined. */
function listLiteral(initializer: ts.Expression | undefined, callees: string[], declared: ReadonlyMap<string, ts.Statement>): ts.ArrayLiteralExpression | undefined {
  if (initializer !== undefined && ts.isArrayLiteralExpression(initializer)) return initializer;
  if (initializer === undefined || !ts.isCallExpression(initializer) || !ts.isIdentifier(initializer.expression) || initializer.arguments.length !== 1) return undefined;
  const [argument] = initializer.arguments;
  if (!ts.isArrayLiteralExpression(argument)) return undefined;
  if (!declared.has(initializer.expression.text)) return undefined;
  callees.push(initializer.expression.text);
  return argument;
}
/** W9: the top-level declarations a node names: every identifier of its code whose name is one's, wherever it stands, but a
 * property access's name (the name after the dot of an expression) and a property assignment's identifier key. */
function namedIn(node: ts.Node, declared: ReadonlyMap<string, ts.Statement>): string[] {
  const names: string[] = [];
  const visit = (child: ts.Node): void => {
    const parent = child.parent;
    const propertyName = (ts.isPropertyAccessExpression(parent) || ts.isPropertyAssignment(parent)) && parent.name === child;
    if (ts.isIdentifier(child) && declared.has(child.text) && !propertyName) names.push(child.text);
    ts.forEachChild(child, visit);
  };
  visit(node);
  return names;
}
/** W9 and ROSTER: a source's rows for each list (the elements of the one top-level array literal its one const declaration spells,
 * directly or as the one argument of a call of a declared plain name) and the shared declarations the rows' probes and presents
 * and the lists' callees name, each statement's text digested without the comments before it. */
function caseReading(source: string, lists: readonly string[]): CaseReading {
  const file = ts.createSourceFile("case-reading.ts", source, ts.ScriptTarget.Latest, true);
  const declared = new Map<string, ts.Statement>();
  const initializers = new Map<string, (ts.Expression | undefined)[]>();
  for (const statement of file.statements) {
    if ((ts.isFunctionDeclaration(statement) || ts.isClassDeclaration(statement)) && statement.name !== undefined) declared.set(statement.name.text, statement);
    if (!ts.isVariableStatement(statement)) continue;
    const constant = (statement.declarationList.flags & ts.NodeFlags.BlockScoped) === ts.NodeFlags.Const;
    for (const declaration of statement.declarationList.declarations) {
      if (!ts.isIdentifier(declaration.name)) continue;
      declared.set(declaration.name.text, statement);
      initializers.set(declaration.name.text, [...(initializers.get(declaration.name.text) ?? []), constant ? declaration.initializer : undefined]);
    }
  }
  const cases: ts.Expression[] = [];
  const callees: string[] = [];
  const rows = lists.map((list): CaseRow[] => {
    const declarations = initializers.get(list) ?? [];
    const array = declarations.length === 1 ? listLiteral(declarations[0], callees, declared) : undefined;
    if (array === undefined) return [];
    return array.elements.map((element): CaseRow => {
      if (!plainElement(element)) return { id: ABSENT, probe: ABSENT, present: ABSENT };
      const id = assignment(element, "id");
      const probe = assignment(element, "probe");
      const present = assignment(element, "present");
      cases.push(...[probe, present].filter((node): node is ts.Expression => node !== undefined));
      return {
        id: id !== undefined && ts.isStringLiteral(id) ? id.text : ABSENT,
        probe: probe === undefined ? ABSENT : sha256(probe.getText(file)),
        present: present === undefined ? ABSENT : sha256(present.getText(file)),
      };
    });
  });
  const reached = new Set<string>();
  const pending = [...cases.flatMap((node) => namedIn(node, declared)), ...callees];
  for (let name = pending.pop(); name !== undefined; name = pending.pop()) {
    if (reached.has(name)) continue;
    reached.add(name);
    const statement = declared.get(name);
    if (statement !== undefined) pending.push(...namedIn(statement, declared));
  }
  return { rows, shared: [...declared].filter(([name]) => reached.has(name)).map(([name, statement]) => ({ name, digest: sha256(statement.getText(file)) })) };
}
