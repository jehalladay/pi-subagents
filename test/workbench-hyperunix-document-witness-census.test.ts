/** The function a holder holds at key as an enumerable own data property, called census-side; true when there was one. */
function callOwn(holder: unknown, key: string): boolean {
  const value = ownData(holder, key, true);
  if (typeof value !== "function") return false;
  Reflect.apply(value, holder, []);
  return true;
}
/** The text of a Uint8Array that is not a Buffer, else undefined. */
const plainBytesText = (value: unknown): string | undefined => (types.isUint8Array(value) && !Buffer.isBuffer(value) ? Buffer.from(value).toString("utf8") : undefined);
const parsedIf = (text: string | undefined, marker: string): unknown => (text?.includes(marker) === true ? JSON.parse(text) : undefined);
/** Whether a text parses as JSON. */
function parsesAsJson(text: string): boolean {
  try {
    JSON.parse(text);
    return true;
  } catch {
    return false;
  }
}
const bytesOf = (text: string): Uint8Array => new Uint8Array(Buffer.from(text));
/** W3: a function a row plants as a data property: it pushes name to calls each time it is called, then returns body's value. */
function recorded<T>(calls: string[], name: string, body: () => T): () => T {
  return () => {
    calls.push(name);
    return body();
  };
}
/** W3 liveness: call, census-side, every function reachable from value through own data properties (accessors and prototypes
 * not followed), each once and before its own properties are visited, a throw caught. */
function callPlanted(value: unknown, seen: Set<unknown> = new Set()): void {
  if (value === null || (typeof value !== "object" && typeof value !== "function") || seen.has(value)) return;
  seen.add(value);
  if (typeof value === "function") {
    try {
      Reflect.apply(value, undefined, []);
    } catch {
      // a planted function that throws when called has recorded the call first
    }
  }
  for (const key of Reflect.ownKeys(value)) {
    const property = Object.getOwnPropertyDescriptor(value, key);
    if (property !== undefined && "value" in property) callPlanted(property.value, seen);
  }
}
/** A namespace whose BINDING holds no documents until its recorded load binding is called (the GP21 members' form). */
function afterLoad(calls: string[], binding: (fill: () => readonly object[]) => PropertyDescriptor): object {
  const cases: object[] = [];
  const namespace = { load: recorded(calls, "load", () => cases.splice(0, cases.length, PLANTED_DOCUMENT)) };
  return Object.defineProperty(namespace, "BINDING", binding(() => cases));
}
/** The after-a-call rows' present read: the binding reads empty, then holds the planted document once load is called. */
function presentAfterLoad(holder: unknown, read: (holder: unknown) => unknown): unknown {
  return isEmptyArray(read(holder)) && callOwn(holder, "load") ? read(holder) : undefined;
}

/** W3, W7 and W10: a row table frozen as its declaration evaluates it - the array, each of its rows and each array and function
 * a row holds - so that no later statement or expression of this file can give a row another probe, present or reading, or its
 * probe or present function an own property; it returns the array it froze. */
function asSpelled<Row extends object>(rows: readonly Row[]): readonly Row[] {
  for (const row of rows) {
    for (const value of Object.values(row)) if (Array.isArray(value) || typeof value === "function") Object.freeze(value);
    Object.freeze(row);
  }
  return Object.freeze(rows);
}

