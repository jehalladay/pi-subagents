  "change", "changes", "changed", "changing", "new", "replace", "replaces", "replaced", "redefine", "redefines", "redefined", "extend",
  "extends", "extended", "amend", "amends", "amended", "modify", "modifies", "modified", "bump", "bumps", "bumped", "migrate",
