/** A text's words: NFKC-folded, camelCase humps and every run between non-alphanumerics split, lower-cased. */
function words(text: string): string[] {
  return text.normalize("NFKC").replace(/([a-z0-9])([A-Z])/g, "$1 $2").replace(/([A-Z]+)([A-Z][a-z])/g, "$1 $2").split(/[^A-Za-z0-9]+/).filter(Boolean).map(word => word.toLowerCase());
}
interface Needle {
  readonly id: string;
  readonly first: string;
  readonly forms: readonly string[];
}
/** Each needle as read: its first word, then its second singular or plural (or both joined into one word). */
const NEEDLE_READINGS: readonly Needle[] = NEEDLES.map((spelling, index) => {
  const [first = "", second = ""] = words(spelling);
  const stem = second.endsWith("s") ? second.slice(0, -1) : second;
  return { id: `N${index + 1}`, first, forms: [stem, `${stem}s`] };
});
function needlesIn(list: readonly string[]): string[] {
  const found = new Set<string>();
  for (let at = 0; at < list.length; at++) {
    const word = list[at] ?? "";
    const next = list[at + 1] ?? "";
    for (const needle of NEEDLE_READINGS) {
      if ((word === needle.first && needle.forms.includes(next)) || needle.forms.some(form => word === `${needle.first}${form}`)) found.add(needle.id);
    }
  }
  return [...found].sort();
}
/** Clause (a)'s needles as git spells the reading: case-insensitive, up to three separator characters between the two words. */
const NEEDLE_PATTERN = NEEDLE_READINGS.map(needle => `${needle.first}[^[:alnum:]]{0,3}(${needle.forms.join("|")})`).join("|");
function inflections(word: string): string[] {
  const stem = word.endsWith("e") ? word.slice(0, -1) : word;
  return [word, `${word}s`, `${word}d`, `${word}r`, `${word}rs`, `${stem}ing`];
}
