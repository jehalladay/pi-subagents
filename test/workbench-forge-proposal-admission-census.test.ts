/** What a pin's witness must carry from its own quote: a row-A pin's subject (the quote's last path-like word: a scope or a reader
 * file) as the witness's scope or file, and every single-quoted word of the quote among the witness's texts. */
function unbound(pin: Pin, witness: JsonValue): string[] {
  const missing: string[] = [];
  if (pin.id.startsWith("A")) {
    const subject = pin.quote.slice(pin.quote.lastIndexOf(" ") + 1);
    const named = isObject(witness) ? (typeof witness.scope === "string" ? witness.scope : typeof witness.file === "string" ? witness.file : "") : "";
    if (!named.endsWith(subject)) missing.push(`subject ${subject}`);
  }
  const texts = textsOf(witness);
  for (const match of pin.quote.matchAll(/'([^']+)'/g)) {
    const word = match[1] ?? "";
    if (!texts.some(text => text.includes(word))) missing.push(`word ${word}`);
  }
  return missing;
}
/** Whether `quotes`, in order, tile the clause (its letter prefix dropped) with only non-alphanumeric separators between them. */
function tiles(clause: string, quotes: readonly string[]): boolean {
  const text = clause.replace(/^\([a-z]\) /, "");
  let at = 0;
  for (const quote of quotes) {
    const found = quote.length === 0 ? -1 : text.indexOf(quote, at);
    if (found < 0 || /[A-Za-z0-9]/.test(text.slice(at, found))) return false;
    at = found + quote.length;
  }
  return !/[A-Za-z0-9]/.test(text.slice(at));
}

