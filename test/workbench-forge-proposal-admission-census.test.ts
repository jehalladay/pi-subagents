type Locator = (value: JsonObject) => JsonObject[];
const objects = (value: JsonValue | undefined): JsonObject[] => (isObject(value) ? [value] : []);
const packagesOf = (source: JsonObject): JsonObject[] => objects(source.data).flatMap(data => (Array.isArray(data.packages) ? data.packages.filter(isObject) : []));
const statesOf = (source: JsonObject): JsonObject[] => packagesOf(source).flatMap(pkg => objects(pkg.last_result_state));
const GATE_POSITIONS: Readonly<Record<string, Locator>> = {
  source: source => [source],
  envelope: source => objects(source.envelope),
  data: source => objects(source.data),
  package: packagesOf,
  state: statesOf,
  basis: source => statesOf(source).flatMap(state => objects(state.invalidation_basis)),
};
const FRAME_POSITIONS: Readonly<Record<string, Locator>> = { frame: frame => [frame], params: frame => objects(frame.params) };
const REPLY_POSITIONS: Readonly<Record<string, Locator>> = { reply: reply => [reply] };
const ALL = "all";
function positionsOf(positions: Readonly<Record<string, Locator>>): string[] {
  return [...Object.keys(positions), ...(Object.keys(positions).length > 1 ? [ALL] : [])];
}
function locate(positions: Readonly<Record<string, Locator>>, position: string): Locator {
  return value => (position === ALL ? unique(Object.values(positions).flatMap(locator => locator(value))) : (positions[position]?.(value) ?? []));
}
interface Planted {
  readonly value: JsonObject;
  readonly added: number;
  readonly overwrites: number;
}
/** A clone of `value` with every PLANT key added at each located object, never overwriting a native key. */
function plant(value: JsonObject, locator: Locator, variant: Variant): Planted {
  const clone = JSON.parse(JSON.stringify(value)) as JsonObject;
  let added = 0;
  let overwrites = 0;
  for (const target of locator(clone)) {
    for (const key of PLANT_KEYS) {
      if (Object.hasOwn(target, key)) overwrites++;
      else {
        target[key] = variant.value();
        added++;
      }
    }
  }
  return { value: clone, added, overwrites };
}

function refusal(error: unknown): JsonObject {
  if (!(error instanceof Error)) return { refused: "thrown", message: String(error) };
  return {
    refused: error.name,
    category: error instanceof CapabilityError ? error.category : null,
    message: error.message,
    ...(error instanceof ForgeEvidenceError && error.freshness !== undefined ? { freshness: error.freshness } : {}),
  };
}
interface GateOutputs {
  readonly invoke: JsonValue;
  readonly topology: JsonValue;
  readonly native: JsonValue;
  readonly evidence: JsonValue;
}
/** Pi's gate.status chain: the injected provider (registry invoke), then the topology projection, the native-evidence metadata and
 * the evidence pane over the provider's result. */
async function gateOutputs(method: string, raw: JsonObject, drive: Drive): Promise<GateOutputs> {
  const registry = new CapabilityRegistry();
  drive.call(registerForgeGateStatus)(registry, { gate: { status: async () => ({ protocolMethod: method, raw }) } }, "0.1.0");
  let result: JsonValue | undefined;
  let invoke: JsonValue;
  try {
    result = await registry.invoke("forge.gate.status", { target: TARGET }, { grants: GRANTS, signal: new AbortController().signal });
    invoke = result;
  } catch (error) {
    invoke = refusal(error);
  }
  if (result === undefined) return { invoke, topology: null, native: null, evidence: null };
  const reading = result;
  let topology: JsonValue;
  try {
    topology = json(drive.call(forgeGateTopology)(reading, { scope: SCOPE, target: TARGET, capturedAt: CAPTURED, observedAt: OBSERVED }));
  } catch (error) {
    topology = refusal(error);
  }
  const native = json(drive.call(nativeEvidence)("forge.gate.status", reading));
  let evidence: JsonValue;
  try {
    evidence = json(await drive.call(readForgeOperationEvidence)(`forge-operation:${OPERATION}`, { grants: () => GRANTS, scope: SCOPE, target: TARGET, read: async () => reading, now: () => CAPTURED }));
  } catch (error) {
    evidence = refusal(error);
  }
  return { invoke, topology, native, evidence };
}
type GateConsumer = (method: string, raw: JsonObject, drive: Drive) => Promise<GateOutputs>;
interface Differential {
  readonly cases: number;
  readonly planted: number;
  readonly vacuous: number;
  readonly overwrites: number;
  readonly divergent: string[];
  readonly echoInexact: string[];
  readonly outputs: { readonly label: string; readonly base: string; readonly outputs: GateOutputs }[];
}
/** Every base x position x variant through `consumer`, against the base's unplanted outputs: the Pi-derived outputs must be equal
 * and the provider's result must be the planted native JSON exactly (or the base's own refusal). */
async function gateDifferential(bases: readonly GateBase[], variants: readonly Variant[], drive: Drive, consumer: GateConsumer = gateOutputs): Promise<Differential> {
  let cases = 0;
  let planted = 0;
  let vacuous = 0;
  let overwrites = 0;
  const divergent: string[] = [];
  const echoInexact: string[] = [];
  const outputs: Differential["outputs"] = [];
  for (const base of bases) {
    const baseline = await consumer(base.method, base.source, drive);
    for (const position of positionsOf(GATE_POSITIONS)) {
      for (const variant of variants) {
        cases++;
        const sown = plant(base.source, locate(GATE_POSITIONS, position), variant);
        if (sown.added === 0) {
          vacuous++;
          continue;
        }
        planted++;
        overwrites += sown.overwrites;
        const label = `${base.id}/${position}/${variant.id}`;
        const out = await consumer(base.method, sown.value, drive);
        if (!same(out.topology, baseline.topology) || !same(out.native, baseline.native) || !same(out.evidence, baseline.evidence)) divergent.push(label);
        const echo = isObject(baseline.invoke) && Object.hasOwn(baseline.invoke, "refused") ? baseline.invoke : { contract: CONTRACT, protocolMethod: "gate.status", source: sown.value };
        if (!same(out.invoke, echo)) echoInexact.push(label);
        outputs.push({ label, base: base.id, outputs: out });
      }
    }
  }
  return { cases, planted, vacuous, overwrites, divergent, echoInexact, outputs };
}
function differentialWitness(run: Differential, bases: readonly GateBase[], variants: readonly Variant[], drive: Drive): JsonObject {
  return {
    bases: bases.map(base => base.id),
    positions: positionsOf(GATE_POSITIONS),
    variants: variants.map(variant => variant.id),
    plantKeys: PLANT_KEYS.length,
    cases: run.cases,
    planted: run.planted,
    vacuous: run.vacuous,
    overwrites: run.overwrites,
    divergent: run.divergent,
    echoInexact: run.echoInexact,
    driven: drive.list(),
  };
}
/** Whether `value` carries `key` as an own key at any depth. */
function carriesKey(value: JsonValue | undefined, key: string): boolean {
  if (Array.isArray(value)) return value.some(item => carriesKey(item, key));
  if (!isObject(value)) return false;
  return Object.hasOwn(value, key) || Object.values(value).some(item => carriesKey(item, key));
}
/** The divergent-twin controls of a gate.status differential: a consumer promoting on a planted key is caught, one promoting on an
 * unplanted key stays quiet (R-UNPLANTED-KEY), and a native field change (the measured row made current) diverges. */
async function twinControls(variants: readonly Variant[]): Promise<JsonObject> {
  const promoting = (key: string): GateConsumer => async (method, raw, drive) => {
    const out = await gateOutputs(method, raw, drive);
    return carriesKey(raw, key) ? { ...out, topology: { promoted: SUCCESS_TONE } } : out;
  };
  const history = NO_RECEIPT.slice(0, 1);
  const caught = await gateDifferential(history, variants.slice(0, 1), new Drive(), promoting(PLANT_KEYS[0] ?? ""));
  const quiet = await gateDifferential(history, variants.slice(0, 1), new Drive(), promoting("confidence"));
  const base = await gateOutputs("gate.status", gateSource([MEASURED_ROW]), new Drive());
  const twin = await gateOutputs("gate.status", gateSource([current()]), new Drive());
  return {
    plantedKeyConsumer: caught.divergent.length === caught.planted && caught.planted > 0 ? "caught" : "missed",
    unplantedKeyConsumer: quiet.divergent.length === 0 ? "quiet" : "caught",
    nativeTwin: same(base.topology, twin.topology) ? "identical" : "divergent",
  };
}

/** Every string in a value, keys included. */
function textsOf(value: JsonValue | undefined): string[] {
  if (typeof value === "string") return [value];
  if (Array.isArray(value)) return value.flatMap(textsOf);
  if (!isObject(value)) return [];
  return Object.entries(value).flatMap(([key, item]) => [key, ...textsOf(item)]);
}
/** What a plant could leave behind: its words, numbers, labels and keys. */
const MARKERS = unique([...PROPOSALS, ...FACETS, String(HIGH_SCORES[0]), String(HIGH_SCORES[2]), ...PLANT_KEYS, "PASS"]);
function markersIn(value: JsonValue | undefined): string[] {
  const texts = textsOf(value);
  return MARKERS.filter(marker => texts.some(text => text.includes(marker)));
}

