/** D2: the verdict vocabulary read off the readers' own receipt and FAIL outputs, and its absence from every no-receipt output. */
async function verdictReading(): Promise<JsonObject> {
  const drive = new Drive();
  const receipt = await receiptReading();
  const tones = unique([String(receipt.tone), String(receipt.failTone)]).sort();
  const qualifiers = unique([String(receipt.qualifier), String(receipt.failQualifier)]).sort();
  const gate = await gateDifferential([...NO_RECEIPT, ...REFUSED], ALL_VARIANTS, drive);
  const operation = operationDifferential(NO_RECEIPT_OPERATION, ALL_VARIANTS, drive);
  const observed = await observedDifferential(OPEN_RUN, ALL_VARIANTS, drive);
  const hits: string[] = [];
  const judge = (label: string, value: JsonValue): void => {
    if (presentations(value).some(entry => tones.includes(entry.tone))) hits.push(`${label} tone`);
    if (textsOf(value).some(text => qualifiers.some(qualifier => text.includes(qualifier)))) hits.push(`${label} qualifier`);
  };
  for (const { label, outputs } of gate.outputs) for (const surface of ["topology", "native", "evidence"] as const) judge(`${label} ${surface}`, outputs[surface]);
  for (const { label, output } of operation.outputs) judge(label, output);
  observed.outputs.forEach((output, index) => {
    judge(`observed/${ALL_VARIANTS[index]?.id}`, output);
  });
  const history = gate.outputs.find(entry => entry.base === "history")?.outputs;
  return {
    vocabulary: { tones, qualifiers },
    readings: gate.planted + operation.planted + observed.outputs.length,
    hits: unique(hits),
    nativeQuote: history === undefined ? "" : (presentations(history.topology)[0]?.text.split(" · ")[0] ?? ""),
    driven: drive.list(),
  };
}

