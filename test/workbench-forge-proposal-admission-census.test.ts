/** A dedicated connection that, when gate.run is requested, delivers `frames` to every sink and answers `reply`. */
function scriptedConnection(frames: readonly JsonObject[], reply: JsonValue): ForgeOperationConnection {
  const sinks = new Set<(frame: ForgeOperationFrame) => void>();
  return {
    capabilities: null,
    operations: {
      cancel: async () => {
        throw new Error("the census issues no control verb");
      },
    },
    onNotification(sink) {
      sinks.add(sink);
      return () => {
        sinks.delete(sink);
      };
    },
    request: async () => {
      for (const value of frames) for (const sink of [...sinks]) sink(asFrame(value));
      return reply;
    },
    close: async () => undefined,
  };
}
/** The observed gate.run end to end (observeForgeGateRun over the scripted connection into a real projection). */
async function observedOutput(run: ObservedRun, drive: Drive): Promise<JsonValue> {
  const projection = new ObservationProjection();
  const observer = await drive.call(observeForgeGateRun)(scriptedConnection(run.frames, run.reply), {
    root: TARGET, projection, scope: SCOPE, now: () => AT, timeoutMs: 30_000, retain: () => () => undefined,
  });
  const settled = await observer.settled;
  await observer.dispose();
  return json({ settled, nodes: projection.query({ scope: SCOPE, limit: 50 }).nodes, relations: projection.relations({ scope: SCOPE }) });
}
