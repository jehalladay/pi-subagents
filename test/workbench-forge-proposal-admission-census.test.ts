const MODULE_KINDS: Readonly<Record<string, ts.ScriptKind>> = {
  ".ts": ts.ScriptKind.TS, ".mts": ts.ScriptKind.TS, ".cts": ts.ScriptKind.TS, ".tsx": ts.ScriptKind.TSX,
  ".js": ts.ScriptKind.JS, ".mjs": ts.ScriptKind.JS, ".cjs": ts.ScriptKind.JS, ".jsx": ts.ScriptKind.JSX,
};
function moduleKind(file: string): ts.ScriptKind | undefined {
  const dot = file.lastIndexOf(".");
  return dot < 0 ? undefined : MODULE_KINDS[file.slice(dot)];
}
function parse(file: string, text: string): ts.SourceFile {
  return ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, moduleKind(file) ?? ts.ScriptKind.TS);
}
/** One module's TOKEN reading: identifier names and the cooked text of every string, template, regular-expression and JSX literal. */
function moduleTokens(file: string, text: string): string[] {
  const tokens: string[] = [];
  const visit = (node: ts.Node): void => {
    if (ts.isIdentifier(node) || ts.isPrivateIdentifier(node)) tokens.push(node.text);
    else if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node) || ts.isTemplateHead(node) || ts.isTemplateMiddle(node) || ts.isTemplateTail(node) || ts.isRegularExpressionLiteral(node) || ts.isJsxText(node)) {
      tokens.push(node.text);
    }
    ts.forEachChild(node, visit);
  };
  visit(parse(file, text));
  return tokens;
}
/** A module's exported declarations: every name, and the names that are functions. */
function exportedNames(file: string, text: string): { names: string[]; functions: string[] } {
  const names: string[] = [];
  const functions: string[] = [];
  for (const statement of parse(file, text).statements) {
    const exported = ts.canHaveModifiers(statement) && (ts.getModifiers(statement) ?? []).some(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword);
    if (!exported) continue;
    if (ts.isFunctionDeclaration(statement) && statement.name) {
      names.push(statement.name.text);
      functions.push(statement.name.text);
    } else if ((ts.isInterfaceDeclaration(statement) || ts.isTypeAliasDeclaration(statement) || ts.isClassDeclaration(statement)) && statement.name) {
      names.push(statement.name.text);
    } else if (ts.isVariableStatement(statement)) {
      for (const declaration of statement.declarationList.declarations) {
        if (!ts.isIdentifier(declaration.name)) continue;
        names.push(declaration.name.text);
        const value = declaration.initializer;
        if (value !== undefined && (ts.isArrowFunction(value) || ts.isFunctionExpression(value))) functions.push(declaration.name.text);
      }
    }
  }
  return { names, functions };
}
/** The body text of an exported function declaration, or undefined. */
function functionBody(file: string, text: string, name: string): ts.Block | undefined {
  for (const statement of parse(file, text).statements) {
    if (ts.isFunctionDeclaration(statement) && statement.name?.text === name) return statement.body;
  }
  return undefined;
}

interface Walk {
  readonly files: string[];
  readonly symlinks: string[];
}
/** Every regular file at or below `entry` (relative to `root`), in name order; a symlink is recorded, never followed. */
function walk(root: string, entry: string): Walk {
  const files: string[] = [];
  const symlinks: string[] = [];
  const visit = (path: string): void => {
    const stat = lstatSync(join(root, path));
    if (stat.isSymbolicLink()) symlinks.push(path);
    else if (stat.isDirectory()) for (const name of readdirSync(join(root, path)).sort()) visit(`${path}/${name}`);
    else if (stat.isFile()) files.push(path);
  };
  if (existsSync(join(root, entry))) visit(entry);
  return { files, symlinks };
}
interface FileReading {
  readonly file: string;
  readonly words: number;
  readonly hits: string[];
}
/** Clause (a)'s reading of one file: the needles its path and its raw words hold and, when `tokens` and the file is a module, its tokens hold. */
function readFile(root: string, file: string, tokens: boolean): FileReading {
  const text = readFileSync(join(root, file), "utf8");
  const raw = words(text);
  const hits = [...needlesIn(words(file)).map(id => `${id} path`), ...needlesIn(raw).map(id => `${id} raw`)];
  if (tokens && moduleKind(file) !== undefined) {
    const found = unique(moduleTokens(file, text).flatMap(token => needlesIn(words(token)))).sort();
    hits.push(...found.map(id => `${id} token`));
  }
  return { file, words: raw.length, hits };
}
/** The SCORE reading of one module text: "raw" when its words hold the token, "token" when a token's words do. */
function scoreHits(file: string, text: string): string[] {
  const hits: string[] = [];
  if (words(text).some(word => TOKEN_WORDS.includes(word))) hits.push("raw");
  if (moduleKind(file) !== undefined && moduleTokens(file, text).some(token => words(token).some(word => TOKEN_WORDS.includes(word)))) hits.push("token");
  return hits;
}
