/** One scope's clause (a) reading: the walk, the readings, the literal grep and the planted controls. */
function scopeReading(scope: string): JsonObject {
  const tree = walk(REPO, scope);
  const tokens = (file: string): boolean => scope !== "test" || !holder(file);
  const readings = tree.files.map(file => readFile(REPO, file, tokens(file)));
  const modules = tree.files.filter(file => moduleKind(file) !== undefined).length;
  const hit = readings.filter(reading => reading.hits.length > 0);
  const grep = literal(["-i", "-E", NEEDLE_PATTERN, "--", scope]);
  const tracked = spawnSync("git", ["ls-files", "-z", "--", scope], { cwd: REPO, encoding: "utf8" });
  const listed = tracked.status === 0 ? tracked.stdout.split("\0").filter(Boolean) : [];
  const grepFiles = unique(grep.lines.map(fileOf)).sort();
  const controls = scope === "src" ? srcControls() : scope === "test" ? testControls() : docsControls();
  const root = plantTree(controls);
  const planted = walk(root, scope).files;
  const classified: JsonObject = {};
  for (const file of Object.keys(controls)) {
    if (!planted.includes(file)) {
      classified[file] = "unwalked";
      continue;
    }
    const reading = readFile(root, file, tokens(file));
    classified[file] = reading.hits.length === 0 ? "quiet" : scope === "test" ? `${holder(file) ? "holder" : "outside"}:${reading.hits.join(",")}` : `hit:${reading.hits.join(",")}`;
  }
  const floor = scope === "src" ? FLOORS.src : scope === "test" ? FLOORS.test : FLOORS.docs;
  const base: JsonObject = {
    scope,
    fileFloor: tree.files.length >= floor,
    trackedFloor: listed.length >= floor,
    trackedUnwalked: listed.filter(file => !tree.files.includes(file)),
    symlinks: tree.symlinks,
    wordless: readings.filter(reading => reading.words === 0).map(reading => reading.file),
  };
  if (scope === "test") {
    return {
      ...base,
      moduleFloor: modules >= FLOORS.testModules,
      outsideHolders: hit.filter(reading => !holder(reading.file)).map(reading => `${reading.file} ${reading.hits.join(",")}`),
      self: [SELF, ROSTER_FILE].map(file => ({ file, walked: tree.files.includes(file), hits: readFile(REPO, file, false).hits.length })),
      literal: { ran: grep.ran, outsideHolders: grepFiles.filter(file => !holder(file)) },
      controls: classified,
    };
  }
  return {
    ...base,
    ...(scope === "src" ? { moduleFloor: modules >= FLOORS.srcModules } : {}),
    hits: hit.map(reading => `${reading.file} ${reading.hits.join(",")}`),
    literal: { ran: grep.ran, files: grepFiles },
    controls: classified,
  };
}
/** One reader file's SCORE reading, its literal grep and its two-instrument liveness; `controls` adds the planted SCORE controls. */
