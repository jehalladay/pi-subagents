/** One varied reading: its name, the reading, and whether it carries what its name says (the placement control). */
interface Cell {
  readonly name: string;
  readonly value: JsonValue;
  readonly landed: boolean;
}
const EVIDENCE: Path = ['source', 'evidence'];
/** Every cell R1, A1 and A2 judge for one base reading: each tier member under each word at every object node of the provider
 * output (its root, runtime and source, and every node below the source), then each evidence-class set. A cell has landed when
 * its node did not hold the member and now holds it at that word, or when the evidence classes now equal a set the base did not
 * carry. */
function* tierCells(base: Base, words: readonly string[], classSets: readonly (readonly string[])[]): Generator<Cell> {
  for (const path of objectPaths(base.reading)) {
    const node = nodeAt(base.reading, path);
    for (const member of TIER_MEMBERS) {
      for (const tier of words) {
        const value = placed(base.reading, path, member, tier);
        yield {name: `${base.name} ${label(path)} ${member}=${tier}`, value, landed: !Object.hasOwn(node, member) && nodeAt(value, path)[member] === tier};
      }
    }
  }
  const bare = nodeAt(base.reading, EVIDENCE).evidence_classes;
  for (const classes of classSets) {
    const value = placed(base.reading, EVIDENCE, 'evidence_classes', [...classes]);
    yield {name: `${base.name} classes ${classes.join(',')}`, value,
      landed: isDeepStrictEqual(nodeAt(value, EVIDENCE).evidence_classes, [...classes]) && !isDeepStrictEqual(bare, [...classes])};
  }
}

