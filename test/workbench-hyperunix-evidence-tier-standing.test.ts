/** One object node of a live input: a node of one frame's body, or (no frame) a node of the transport diagnostic. */
interface LiveSite {
  readonly label: string;
  readonly frame?: number;
  readonly path: Path;
}
/** Every object node of a live input's frame bodies, in frame order, then every node of its transport diagnostic. */
const liveSites = (frames: readonly FrameSpec[], transportDiagnostic: Json): LiveSite[] => [
  ...frames.flatMap(([kind, body], frame) => objectPaths(body).map(path => ({label: path.length === 0 ? kind : `${kind}.${label(path)}`, frame, path}))),
  ...objectPaths(transportDiagnostic).map(path => ({label: path.length === 0 ? 'transport-diagnostic' : `transport-diagnostic.${label(path)}`, path})),
];
/** What one live cell reads: a decoder refusal (the member's own name in its path written <member>), a member rebuilt away, or the
 * provider-output nodes that carry it at that value; with the provider output when the input decodes. */
async function liveCell(frames: readonly FrameSpec[], transportDiagnostic: Json, site: LiveSite, member: string, value: JsonValue):
  Promise<{readonly outcome: string; readonly reading?: JsonValue; readonly carriers: readonly Path[]}> {
  const tiered = frames.map(([kind, body, batch, envelope], index): FrameSpec =>
    [kind, index === site.frame ? asRecord(withMember(body, site.path, member, value)) : body, batch, envelope]);
  const transport = site.frame === undefined ? asRecord(withMember(transportDiagnostic, site.path, member, value)) : transportDiagnostic;
  let result: QueryResult<ClaimBody>;
  try {
    result = liveResultOf(tiered, transport);
  } catch (error) {
    if (!(error instanceof ProtocolError)) throw error;
    return {outcome: `refused ${error.code} ${(error.path ?? '').replace(member, '<member>')} ${error.nativeCode ?? ''}`, carriers: []};
  }
  const reading = await providedResult(result);
  const carriers = objectPaths(reading).filter(path => isDeepStrictEqual(nodeAt(reading, path)[member], value));
  return {outcome: carriers.length === 0 ? 'rebuilt away' : `carried to ${carriers.map(label).join(', ')}`, reading, carriers};
}
/** A provider output with a member deleted from the nodes that carry it: equal to the twin's when nothing else changed. */
function stripped(reading: JsonValue, carriers: readonly Path[], member: string): JsonValue {
  const copy = json(reading);
  for (const path of carriers) delete nodeAt(copy, path)[member];
  return copy;
}

const INDEX = /^(?:0|[1-9]\d*)$/;
/** Wraps a JSON value in proxies that record each field read through them as a dotted path from the root, the instrument of
 * test/workbench-hyperunix-consumed-fields.test.ts (THE INSTRUMENT there, traced()): an object member is '<path>.<key>' (a member
 * the value lacks included), any element of a list '<path>[]', a list's length the list's own path, and an enumeration of an
 * object's keys '<path>.*' ('*' at the root); gets, `in` checks and own-descriptor reads are recorded, a prototype member is not. */
function traced(value: JsonValue, reads: Set<string>, path = ''): JsonValue {
  if (typeof value !== 'object' || value === null) return value;
  const list = Array.isArray(value);
  const at = (key: string): string => {
    if (list && key === 'length') return path;
    if (list && INDEX.test(key)) return `${path}[]`;
    return path === '' ? key : `${path}.${key}`;
  };
  const field = (target: object, key: string | symbol): key is string =>
    typeof key === 'string' && (Object.hasOwn(target, key) || !Reflect.has(target, key));
  const wrapped = (key: string, item: unknown): unknown =>
    list && key === 'length' ? item : traced(item as JsonValue, reads, at(key));
  return new Proxy(value, {
    get(target, key, receiver) {
      const item: unknown = Reflect.get(target, key, receiver);
      if (!field(target, key)) return item;
      reads.add(at(key));
      return wrapped(key, item);
    },
    has(target, key) {
      if (field(target, key)) reads.add(at(key));
      return Reflect.has(target, key);
    },
    getOwnPropertyDescriptor(target, key) {
      const descriptor = Reflect.getOwnPropertyDescriptor(target, key);
      if (!field(target, key)) return descriptor;
      reads.add(at(key));
      return descriptor && 'value' in descriptor ? {...descriptor, value: wrapped(key, descriptor.value)} : descriptor;
    },
    ownKeys(target) {
      reads.add(path === '' ? '*' : `${path}.*`);
      return Reflect.ownKeys(target);
    },
  });
}
type ReaderName = 'adapter' | 'invariant' | 'native';
/** The three readers of a hyperunix.find provider output. */
