function treeTexts(tree: string, paths: readonly string[]): FileText[] {
  const out = execFileSync("git", ["cat-file", "--batch"], { cwd: REPO, input: `${paths.map(path => `${tree}:${path}`).join("\n")}\n`, maxBuffer: 512 * 1024 * 1024 });
  const files: FileText[] = [];
  let at = 0;
  for (const path of paths) {
    const end = out.indexOf(10, at);
    const header = out.subarray(at, end).toString("utf8").split(" ");
    if (header[1] !== "blob") throw new Error(`${tree}:${path} is not a blob (${header.join(" ")})`);
    const size = Number(header[2]);
    files.push({ path, text: out.subarray(end + 1, end + 1 + size).toString("utf8") });
    at = end + 1 + size + 1;
  }
  return files;
}

