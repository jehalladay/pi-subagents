const nameOf = (node: ts.Node): string | undefined => {
  if (ts.isPropertyAccessExpression(node)) return node.name.text;
  if (ts.isElementAccessExpression(node) && ts.isStringLiteralLike(node.argumentExpression)) return node.argumentExpression.text;
  return undefined;
};
const named = (node: ts.Expression, name: string): boolean => (ts.isIdentifier(node) && node.text === name) || nameOf(node) === name;
/** The value a member read is taken off, with the parentheses, type assertions, non-null assertions and satisfies clauses around
 * it seen through (wb-mymm F1: output!, (output as T), (output), (output satisfies T) and (<T>output) all name output). */
function unwrapped(node: ts.Expression): ts.Expression {
  let current = node;
  while (
    ts.isParenthesizedExpression(current) || ts.isAsExpression(current) || ts.isNonNullExpression(current) ||
    ts.isSatisfiesExpression(current) || ts.isTypeAssertionExpression(current)
  ) current = current.expression;
  return current;
}
/** A3's accessor a member read names: output.text (a `text` member of a value named output, its wrappers seen through) or a
 * payload-reference field. */
function accessorOf(node: ts.Node): string | undefined {
  if (!ts.isPropertyAccessExpression(node) && !ts.isElementAccessExpression(node)) return undefined;
  const name = nameOf(node);
  if (name === "text" && named(unwrapped(node.expression), "output")) return "output.text";
  return name !== undefined && PAYLOAD_FIELDS.includes(name) ? name : undefined;
}
/** The expression a read is used as: parentheses and type assertions around it are seen through. */
function usePosition(node: ts.Node): ts.Node {
  let current = node;
  while (
    ts.isParenthesizedExpression(current.parent) || ts.isAsExpression(current.parent) || ts.isNonNullExpression(current.parent) ||
    ts.isSatisfiesExpression(current.parent) || ts.isTypeAssertionExpression(current.parent)
  ) current = current.parent;
  return current;
}
/** The statement a node sits in: the outermost ancestor below a block, a case clause or the file. */
function statementOf(node: ts.Node): ts.Node {
  let current = node;
  while (
    !ts.isSourceFile(current.parent) && !ts.isBlock(current.parent) && !ts.isModuleBlock(current.parent) && !ts.isCaseClause(current.parent) &&
    !ts.isDefaultClause(current.parent)
  ) current = current.parent;
  return current;
}
/** Whether a comment attached to the node's statement (leading, or trailing on its line) says text-only. */
function labelled(text: string, node: ts.Node): boolean {
  const statement = statementOf(node);
  const ranges = [...(ts.getLeadingCommentRanges(text, statement.pos) ?? []), ...(ts.getTrailingCommentRanges(text, statement.end) ?? [])];
  return ranges.some(range => TEXT_ONLY.test(text.slice(range.pos, range.end)));
}
const calleeName = (callee: ts.Expression): string | undefined =>
  ts.isIdentifier(callee) ? callee.text : ts.isPropertyAccessExpression(callee) ? callee.name.text : undefined;
const isAbsent = (node: ts.Expression): boolean => node.kind === ts.SyntaxKind.NullKeyword || (ts.isIdentifier(node) && node.text === "undefined");
const EQUALITY: readonly ts.SyntaxKind[] = [
  ts.SyntaxKind.EqualsEqualsEqualsToken, ts.SyntaxKind.ExclamationEqualsEqualsToken, ts.SyntaxKind.EqualsEqualsToken, ts.SyntaxKind.ExclamationEqualsToken,
];
/** A3's use class of one accessor read. */
function classOf(node: ts.Node, text: string): string {
  const use = usePosition(node);
  const parent = use.parent;
  const compared = (): string => (labelled(text, use) ? "comparison-labelled" : "comparison");
  if (ts.isTypeOfExpression(parent)) return "type-guard";
  if (ts.isBinaryExpression(parent) && EQUALITY.includes(parent.operatorToken.kind)) {
    return isAbsent(parent.left === use ? parent.right : parent.left) ? "presence" : compared();
  }
  if (ts.isCallExpression(parent) && parent.arguments.some(argument => argument === use)) {
    const callee = calleeName(parent.expression);
    if (callee === "update") return "digest";
    if (callee !== undefined && COMPARING_CALLS.includes(callee)) return compared();
  }
  if (ts.isPropertyAccessExpression(parent) && parent.expression === use && parent.name.text === "localeCompare") return compared();
  if ((ts.isSwitchStatement(parent) || ts.isCaseClause(parent)) && parent.expression === use) return compared();
  if (ts.isComputedPropertyName(parent)) return compared();
  return "read";
}
/** One module's code tokens spelling PARITY_WORD (A1) or CLASS_WORD (T1), its comment mentions of PARITY_WORD (A2) and its
 * classified accessor reads (A3), in source order. */
function scanCode(fileName: string, text: string): CodeScan {
  const source = ts.createSourceFile(fileName, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  const parity: string[] = [];
  const classes: string[] = [];
  const sites: string[] = [];
  const seen = new Set<number>();
  let comments = 0;
  const commentsAt = (ranges: readonly ts.CommentRange[] | undefined): void => {
    for (const range of ranges ?? []) {
      if (seen.has(range.pos)) continue;
      seen.add(range.pos);
      comments += text.slice(range.pos, range.end).match(PARITY_WORDS)?.length ?? 0;
    }
  };
  const token = (kind: string, value: string): void => {
    if (PARITY_WORD.test(value)) parity.push(`${fileName}: ${kind} ${value}`);
    if (CLASS_WORD.test(value)) classes.push(`${fileName}: ${kind} ${value}`);
  };
  const visit = (node: ts.Node): void => {
    commentsAt(ts.getLeadingCommentRanges(text, node.pos));
    commentsAt(ts.getTrailingCommentRanges(text, node.end));
    if (ts.isIdentifier(node) || ts.isPrivateIdentifier(node)) token("identifier", node.text);
    else if (ts.isStringLiteralLike(node)) token("literal", node.text);
    else if (ts.isTemplateExpression(node)) {
      // Parts join on a marker, never a space, so a word cannot form across a ${} (pari${x}ty spells nothing).
      token("template", [node.head.text, ...node.templateSpans.map(span => span.literal.text)].join("<expr>"));
    } else if (ts.isRegularExpressionLiteral(node)) token("regex", node.text);
    const accessor = accessorOf(node);
    if (accessor !== undefined) sites.push(`${accessor}:${classOf(node, text)}`);
    ts.forEachChild(node, visit);
  };
  visit(source);
  return { parity, classes, comments, sites };
}
