/** One frozen-shape entry per row: what the row judges and the sha256 (first 16 hex) of its two wordings. */
const digest = (text: string): string => createHash("sha256").update(text, "utf8").digest("hex").slice(0, 16);
const shapeOf = (row: Row): string => [row.requirement, row.id, row.claim, row.status, row.transform, row.where, row.kind, row.pins.join("+"), digest(row.existing), digest(row.repair)].join("|");

interface Place {
  readonly page: PageKey;
  readonly first: number;
  readonly last: number;
}
const isPageKey = (key: string): key is PageKey => Object.hasOwn(PAGES, key);
/** A Where cell (01:L9, 02:L36-42, README:L4) as its page and line range. */
function placeOf(row: Row): Place {
  const match = /^(README|SKILL|0[1-4]):L(\d+)(?:-(\d+))?$/.exec(row.where);
  if (match === null) throw new Error(`${row.id}: unreadable Where ${row.where}`);
  const [, key = "", first = "", last] = match;
  if (!isPageKey(key)) throw new Error(`${row.id}: unknown page ${key}`);
  return { page: key, first: Number(first), last: Number(last ?? first) };
}
const byId = new Map(ROWS.map(row => [row.id, row] as const));
const byClaim = new Map(ROWS.map(row => [row.claim, row] as const));
/** The kind REMEDIATION's own words give a row: "ledger only:" leads a ledger-only Repair, "same edit as C<nnnn>" names a host. */
function kindOfWords(row: Row): Kind {
  if (row.repair.startsWith("ledger only:")) return "ledger-only";
  return /same edit as C\d+/.test(row.repair) ? "same-edit" : "edit";
}
function hostOf(row: Row): Row {
  const claim = /same edit as (C\d+)/.exec(row.repair)?.[1];
  const host = claim === undefined ? undefined : byClaim.get(claim);
  if (host === undefined) throw new Error(`${row.id}: no host row for ${claim ?? "its same edit"}`);
  return host;
}
/** The text that must stand on the row's line: the Repair, the host's Repair, or (ledger-only) the norm left in place. */
function standingOf(row: Row): string {
  if (row.kind === "ledger-only") return row.existing;
  return row.kind === "same-edit" ? hostOf(row).repair : row.repair;
}
/** The overstrong wording a restore puts back: the row's Existing wording, or a same-edit row's host's. */
const restoredOf = (row: Row): string => (row.kind === "same-edit" ? hostOf(row).existing : row.existing);

const pageText = (key: PageKey): string => readFileSync(join(ROOT, PAGES[key]), "utf8");
const lineAt = (text: string, index: number): number => text.slice(0, index).split("\n").length;
/** Every start index of `needle` in `text`, overlapping occurrences included. */
function occurrences(text: string, needle: string): number[] {
  const at: number[] = [];
  for (let index = text.indexOf(needle); index !== -1; index = text.indexOf(needle, index + 1)) at.push(index);
  return at;
}

/** The Markdown token kinds this census reads as text a reader is shown: exactly the kinds the six pages use today. */
const SHOWN: ReadonlySet<string> = new Set(["space", "hr", "heading", "paragraph", "text", "strong", "em", "codespan", "code", "list", "list_item", "table", "link"]);
/** What SHOWN reads as HIDDEN on a page (marked's GFM lexer, every token walked; the code below is the reading). What
 * this census claims of it is exactly its plants - the header's HIDDEN paragraph (the hidden-forms, whitespace and title
 * plants, and HIDDEN-COMMENT and HIDDEN-ATTRIBUTE); a form spelled otherwise is NOT CLAIMED. Each form once, in the order
 * the walk meets it. */
function hiddenFormsOf(text: string): string[] {
  const forms = new Set<string>();
  walkTokens(new Lexer({ gfm: true }).lex(text), token => {
    if (!SHOWN.has(token.type)) forms.add(token.type);
    else if (token.type === "link") {
      const link = token as Tokens.Link;
      if (typeof link.title === "string") forms.add("link title");
      if (/\s/.test(link.href)) forms.add("link destination");
    } else if (token.type === "code" && /\s/.test((token as Tokens.Code).lang ?? "")) forms.add("code info");
  });
  return [...forms];
}
/** Whether `standing` lies inside a code block of the page: a reader is shown a code block's text as code, an HTML form included. */
function inCodeBlock(text: string, standing: string): boolean {
  let inside = false;
  walkTokens(new Lexer({ gfm: true }).lex(text), token => {
    if (token.type === "code" && (token as Tokens.Code).text.includes(standing)) inside = true;
  });
  return inside;
}
/** The longest k below the Existing wording's length with the standing text's last k characters equal to the Existing
 * wording's first k (0 when none): the Existing wording glued there starts inside the standing text and ends after it. */
function endOverlap(standing: string, existing: string): number {
  for (let k = Math.min(standing.length, existing.length - 1); k > 0; k -= 1) if (standing.endsWith(existing.slice(0, k))) return k;
  return 0;
}
/** The longest k below the Existing wording's length with the standing text's first k characters equal to the Existing
 * wording's last k (0 when none): the Existing wording glued there starts before the standing text and ends inside it. */
function startOverlap(standing: string, existing: string): number {
  for (let k = Math.min(standing.length, existing.length - 1); k > 0; k -= 1) if (standing.startsWith(existing.slice(existing.length - k))) return k;
  return 0;
}
