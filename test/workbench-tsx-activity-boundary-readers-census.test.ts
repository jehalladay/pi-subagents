const rosterLine = (falsifier: Falsifier): string => ` *   ${falsifier.id} ${falsifier.outbox} ${falsifier.row} ${falsifier.pin} ${falsifier.keys.join(",")}: ${falsifier.reading}`;
const witnessForms = (pin: string): Record<string, unknown> => {
  const witness = WITNESS[pin];
  const forms = witness !== null && typeof witness === "object" && !Array.isArray(witness) ? witness.forms : undefined;
  return forms !== null && typeof forms === "object" && !Array.isArray(forms) ? forms : {};
};

