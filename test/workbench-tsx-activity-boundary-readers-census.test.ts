/** A scratch repository (the scratch's repo/ directory) holding `files` (a path ending in "/" is a directory), and `outside`
 * written beside it, outside the repository. */
function tree(files: readonly string[], outside: readonly string[] = []): string {
  const dir = makeScratch("km7q12-readers-");
  scratches.push(dir);
  const base = join(dir, "repo");
  mkdirSync(base, { recursive: true });
  for (const path of outside) writeFileSync(join(dir, path), "export const zz = 1;\n");
  for (const path of files) {
    if (path.endsWith("/")) {
      mkdirSync(join(base, path), { recursive: true });
      continue;
    }
    mkdirSync(dirname(join(base, path)), { recursive: true });
    writeFileSync(join(base, path), "export const zz = 1;\n");
  }
  return base;
}
