function exportRowOf(bead: string): ExportRow {
  const cached = rowCache.get(bead);
  if (cached !== undefined) return cached;
  const rows = readFileSync(join(REPO, EXPORT), "utf8")
    .split("\n")
    .filter(line => line.includes(`"${bead}"`))
    .map(line => JSON.parse(line) as Record<string, unknown>)
    .filter(row => row.id === bead);
  const row = rows.length === 1 ? (rows[0] ?? {}) : {};
  const text = (field: string): string => {
    const value = row[field];
    return typeof value === "string" ? value : "";
  };
  const read = { title: text("title"), description: text("description"), notes: text("notes") };
  rowCache.set(bead, read);
  return read;
}
/** This bead's row of the tracked export. */
const exportRow = (): ExportRow => exportRowOf(BEAD);
/** The lines of a block comment from the line opening with `opener` to the next empty comment line. */
function blockOf(text: string, opener: string): string[] {
  const lines = (text.split("*/", 1)[0] ?? "").split("\n");
  const start = lines.findIndex(line => line.startsWith(opener));
  if (start < 0) return [];
  const end = lines.findIndex((line, index) => index > start && line === " *");
  return lines.slice(start + 1, end < 0 ? lines.length : end);
}
const claimLine = (line: ClaimLine): string => ` * ${line.id} [${line.pins.join(" ")}] ${line.text}`;
const rosterLine = (falsifier: Falsifier): string => ` *   ${falsifier.id} ${falsifier.outbox} ${falsifier.row} ${falsifier.pin} ${falsifier.keys.join(",")}: ${falsifier.reading}`;
const witnessForms = (pin: string): Record<string, unknown> => {
  const witness = WITNESS[pin];
  const forms = witness !== null && typeof witness === "object" && !Array.isArray(witness) ? witness.forms : undefined;
  return forms !== null && typeof forms === "object" && !Array.isArray(forms) ? forms : {};
};

