    const ruling = notes.split("\n").find(line => line.startsWith("ORCHESTRATOR RULING R-B150 ")) ?? "";
    expect(/: U1 - (.+?) \(census /.exec(ruling)?.[1]).toBe(ROWS.find(row => row.id === "SPEC")?.label);
